//! Module-level items: constants, enums, structs, implementations, functions, `main`.

use super::{
    FnGen, GResult, Gen, Helper, Mode, Repr, Want, pascal, screaming, snake, string_literal,
};
use crate::ast::*;
use crate::infer::{EnumKind, EnumValue, Role, StructKind};
use crate::types::Ty;

impl<'a> Gen<'a> {
    pub(super) fn module(&mut self) -> GResult<String> {
        let mut header = String::new();
        if !self.opts.no_header {
            let from = self
                .opts
                .file_name
                .as_deref()
                .map_or(String::new(), |f| format!(" from {f}"));
            header.push_str(&format!(
                "// Generated by Solidify{from}: TypeScript in, Rust out.\n"
            ));
            header.push_str("// https://github.com/maxlestage/Solidify\n\n");
        }
        // Items are written into the buffer; `use` lines and helpers are decided after.
        self.consts()?;
        for en in &self.p.enums.clone() {
            self.enum_item(en)?;
        }
        for u in &self.p.unions.clone() {
            self.union_item(u)?;
        }
        for s in &self.p.structs.clone() {
            self.struct_item(s)?;
        }
        for s in &self.m.body {
            if let StmtKind::Func(f) = &s.kind
                && f.id != usize::MAX
            {
                self.blank();
                for c in &s.comments {
                    self.line(&format!("/// {c}"));
                }
                self.function_item(f, None)?;
            }
        }
        if self.p.has_main {
            self.main_item()?;
        }
        let body = std::mem::take(&mut self.out);
        let mut out = header;
        if !self.p.has_main {
            out.push_str("#![allow(dead_code)]\n\n");
        }
        if self.uses_hashmap && self.uses_hashset {
            out.push_str("use std::collections::{HashMap, HashSet};\n\n");
        } else if self.uses_hashmap {
            out.push_str("use std::collections::HashMap;\n\n");
        } else if self.uses_hashset {
            out.push_str("use std::collections::HashSet;\n\n");
        }
        out.push_str(body.trim_start_matches('\n'));
        let union_impls = self.union_impls()?;
        out.push_str(&union_impls);
        let impls = self.inspect_impls()?;
        for h in self.helpers.clone() {
            out.push('\n');
            out.push_str(h.source());
            out.push('\n');
        }
        out.push_str(&impls);
        Ok(out)
    }

    /// `JsInspect` for the structs and enums that `console.log` shows.
    fn inspect_impls(&mut self) -> GResult<String> {
        let mut out = String::new();
        if !self.helpers.contains(&Helper::Inspect) {
            return Ok(out);
        }
        if self.helpers.contains(&Helper::JsMap) {
            out.push_str(
                "\nimpl<K: JsInspect + std::hash::Hash + Eq + Clone, V: JsInspect> JsInspect for JsMap<K, V> {\n    fn js_value(&self) -> JsValue {\n        JsValue::Map(self.iter().map(|(k, v)| (k.js_value(), v.js_value())).collect())\n    }\n}\n",
            );
        }
        if self.helpers.contains(&Helper::JsSet) {
            out.push_str(
                "\nimpl<T: JsInspect + std::hash::Hash + Eq + Clone> JsInspect for JsSet<T> {\n    fn js_value(&self) -> JsValue {\n        JsValue::Set(self.iter().map(JsInspect::js_value).collect())\n    }\n}\n",
            );
        }
        // Fields may bring in more types: loop until the set is stable.
        let mut done = std::collections::BTreeSet::new();
        loop {
            let pending: Vec<String> = self
                .inspected
                .iter()
                .filter(|n| !done.contains(*n))
                .cloned()
                .collect();
            if pending.is_empty() {
                break;
            }
            for name in pending {
                done.insert(name.clone());
                let rust_name = pascal(&name);
                out.push_str(&format!(
                    "\nimpl JsInspect for {rust_name} {{\n    fn js_value(&self) -> JsValue {{\n"
                ));
                if let Some(u) = self.p.union_info(&name).cloned() {
                    out.push_str("        match self {\n");
                    for m in &u.members {
                        let inner = self.js_value_of("v", &m.ty);
                        out.push_str(&format!(
                            "            {rust_name}::{}(v) => {inner},\n",
                            m.name
                        ));
                    }
                    out.push_str("        }\n");
                } else if let Some(en) = self.p.enum_info(&name).cloned() {
                    if en.kind == EnumKind::Numeric {
                        out.push_str("        match self {\n");
                        for v in &en.variants {
                            let value = match &v.value {
                                Some(EnumValue::Num(n)) if n.fract() == 0.0 => {
                                    format!("JsValue::Int({})", *n as i64)
                                }
                                Some(EnumValue::Num(n)) => format!("JsValue::Float({n:?})"),
                                _ => "JsValue::Str(self.to_string())".to_string(),
                            };
                            out.push_str(&format!(
                                "            {rust_name}::{} => {value},\n",
                                v.name
                            ));
                        }
                        out.push_str("        }\n");
                    } else {
                        out.push_str("        JsValue::Str(self.to_string())\n");
                    }
                } else if let Some(info) = self.p.struct_info(&name).cloned() {
                    let class = if info.kind == StructKind::Class {
                        format!("Some({})", string_literal(&name))
                    } else {
                        "None".to_string()
                    };
                    let mut entries = Vec::new();
                    let mut optional = Vec::new();
                    for f in &info.fields {
                        let key = string_literal(&f.name);
                        let field = snake(&f.name);
                        let value = match self.resolve(&f.ty) {
                            Ty::Func(_) => format!("JsValue::Func({key})"),
                            _ if f.optional && info.kind == StructKind::Class => {
                                // A declared class field exists, `undefined` until set.
                                let inner = self.js_value_of("v", &f.ty);
                                format!(
                                    "self.{field}.as_ref().map_or(JsValue::Undefined, |v| {inner})"
                                )
                            }
                            _ if f.optional => {
                                let inner = self.js_value_of("v", &f.ty);
                                optional.push((key, field, inner));
                                continue;
                            }
                            _ => self.js_value_of(&format!("self.{field}"), &f.ty),
                        };
                        entries.push(format!("({key}.to_string(), {value})"));
                    }
                    if optional.is_empty() {
                        out.push_str(&format!(
                            "        JsValue::Object({class}, vec![{}])\n",
                            entries.join(", ")
                        ));
                    } else {
                        out.push_str(&format!(
                            "        let mut props: Vec<(String, JsValue)> = vec![{}];\n",
                            entries.join(", ")
                        ));
                        for (key, field, inner) in optional {
                            out.push_str(&format!(
                                "        if let Some(v) = &self.{field} {{\n            props.push(({key}.to_string(), {inner}));\n        }}\n"
                            ));
                        }
                        out.push_str(&format!("        JsValue::Object({class}, props)\n"));
                    }
                }
                out.push_str("    }\n}\n");
            }
        }
        Ok(out)
    }

    /// Top-level `const`s holding literals.
    fn consts(&mut self) -> GResult<()> {
        let mut written = false;
        for s in &self.m.body {
            let StmtKind::Var(v) = &s.kind else { continue };
            for d in &v.decls {
                let Pattern::Ident { id, span, .. } = &d.pat else {
                    continue;
                };
                let var = self.p.var(*id);
                if !var.const_literal {
                    continue;
                }
                let init = d.init.as_ref().expect("literal");
                let ty = self.resolve(&var.ty);
                let name = self.bind(
                    *id,
                    if self.is_str(&ty) {
                        Repr::Str
                    } else {
                        Repr::Owned
                    },
                );
                let (t, value) = if self.is_str(&ty) {
                    let ExprKind::Str(s) = &init.kind else {
                        unreachable!()
                    };
                    ("&str".to_string(), string_literal(s))
                } else {
                    let x = self.expr(init)?;
                    (self.rust_ty(&ty, *span)?, x.code)
                };
                let vis = if v.exported { "pub " } else { "" };
                for c in &s.comments {
                    self.line(&format!("/// {c}"));
                }
                self.line(&format!("{vis}const {name}: {t} = {value};"));
                written = true;
            }
        }
        if written {
            self.blank();
        }
        Ok(())
    }

    fn enum_item(&mut self, en: &crate::infer::EnumInfo) -> GResult<()> {
        self.blank();
        let name = pascal(&en.name);
        let vis = if en.exported { "pub " } else { "" };
        self.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
        self.line(&format!("{vis}enum {name} {{"));
        self.indent += 1;
        for v in &en.variants {
            self.line(&format!("{},", v.name));
        }
        self.indent -= 1;
        self.line("}");
        self.blank();
        // Printing gives the JavaScript value.
        self.line(&format!("impl std::fmt::Display for {name} {{"));
        self.indent += 1;
        self.line("fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {");
        self.indent += 1;
        self.line("f.write_str(match self {");
        self.indent += 1;
        for v in &en.variants {
            let text = match (&v.value, en.kind) {
                (Some(EnumValue::Str(s)), _) => string_literal(s),
                (Some(EnumValue::Num(n)), _) => string_literal(&format_num(*n)),
                (None, EnumKind::Literals) => string_literal(&v.source),
                (None, _) => string_literal(&v.source),
            };
            self.line(&format!("{name}::{} => {text},", v.name));
        }
        self.indent -= 1;
        self.line("})");
        self.indent -= 1;
        self.line("}");
        self.indent -= 1;
        self.line("}");
        Ok(())
    }

    /// The enum of a union of different types.
    fn union_item(&mut self, u: &crate::infer::UnionInfo) -> GResult<()> {
        self.blank();
        let name = pascal(&u.name);
        let vis = if u.exported { "pub " } else { "" };
        for c in u.members.iter().map(|m| m.name.clone()).take(0) {
            let _ = c;
        }
        self.line("#[derive(Debug, Clone, PartialEq)]");
        self.line(&format!("{vis}enum {name} {{"));
        self.indent += 1;
        for m in &u.members {
            let t = self.rust_ty(&m.ty, u.span)?;
            self.line(&format!("{}({t}),", m.name));
        }
        self.indent -= 1;
        self.line("}");
        Ok(())
    }

    /// Accessors of the fields read on union values, and `js_typeof`.
    fn union_impls(&mut self) -> GResult<String> {
        let mut out = String::new();
        for u in self.p.unions.clone() {
            let name = pascal(&u.name);
            let accessors: Vec<(String, bool)> = self
                .union_accessors
                .iter()
                .filter(|(en, _, _)| *en == u.name)
                .map(|(_, f, m)| (f.clone(), *m))
                .collect();
            let typeof_wanted = self.union_typeof.contains(&u.name);
            if accessors.is_empty() && !typeof_wanted {
                continue;
            }
            out.push_str(&format!("\nimpl {name} {{\n"));
            let mut first = true;
            let mut done = std::collections::BTreeSet::new();
            for (field, mutable) in accessors {
                for m in [false, mutable] {
                    if !done.insert((field.clone(), m)) {
                        continue;
                    }
                    if !first {
                        out.push('\n');
                    }
                    first = false;
                    let fty = u
                        .members
                        .first()
                        .and_then(|member| match self.resolve(&member.ty) {
                            Ty::Named(n) => self.p.struct_info(&n).and_then(|s| {
                                s.field(&field).map(|f| {
                                    if f.optional {
                                        Ty::Option(Box::new(f.ty.clone()))
                                    } else {
                                        f.ty.clone()
                                    }
                                })
                            }),
                            _ => None,
                        })
                        .unwrap_or(Ty::Any);
                    let t = self.rust_ty(&fty, u.span)?;
                    let f = snake(&field);
                    let (suffix, amp, selfp) = if m {
                        ("_mut", "&mut ", "&mut self")
                    } else {
                        ("", "&", "&self")
                    };
                    out.push_str(&format!(
                        "    fn {f}{suffix}({selfp}) -> {amp}{t} {{\n        match self {{\n"
                    ));
                    for member in &u.members {
                        out.push_str(&format!(
                            "            {name}::{}(v) => {amp}v.{f},\n",
                            member.name
                        ));
                    }
                    out.push_str("        }\n    }\n");
                }
            }
            if typeof_wanted {
                if !first {
                    out.push('\n');
                }
                out.push_str("    fn js_typeof(&self) -> &'static str {\n        match self {\n");
                for member in &u.members {
                    let word = match self.resolve(&member.ty) {
                        Ty::Num(_) => "number",
                        Ty::Str => "string",
                        Ty::Bool => "boolean",
                        Ty::Func(_) => "function",
                        _ => "object",
                    };
                    out.push_str(&format!(
                        "            {name}::{}(_) => \"{word}\",\n",
                        member.name
                    ));
                }
                out.push_str("        }\n    }\n");
            }
            out.push_str("}\n");
        }
        Ok(out)
    }

    fn struct_item(&mut self, s: &crate::infer::StructInfo) -> GResult<()> {
        self.blank();
        let name = pascal(&s.name);
        let vis = if s.exported || s.kind == StructKind::Synth {
            "pub "
        } else {
            ""
        };
        self.line("#[derive(Debug, Clone, PartialEq)]");
        self.line(&format!("{vis}struct {name} {{"));
        self.indent += 1;
        for f in &s.fields {
            let ty = if f.optional {
                Ty::Option(Box::new(f.ty.clone()))
            } else {
                f.ty.clone()
            };
            let t = self.rust_ty(&ty, f.span)?;
            let fvis = match f.access {
                Some(Access::Private) | Some(Access::Protected) => "",
                _ => "pub ",
            };
            self.line(&format!("{fvis}{}: {t},", snake(&f.name)));
        }
        self.indent -= 1;
        self.line("}");
        if s.kind != StructKind::Class {
            return Ok(());
        }
        let class = self.class_asts.get(&s.name).copied().expect("class ast");
        let has_impl = s.ctor.is_some() || !s.methods.is_empty() || !s.statics.is_empty();
        if !has_impl {
            return Ok(());
        }
        self.blank();
        self.line(&format!("impl {name} {{"));
        self.indent += 1;
        let mut first = true;
        for (sname, sty, init) in &s.statics {
            let Some(init_id) = init else {
                return self.err(
                    format!("static field `{sname}` needs a literal value"),
                    s.span,
                );
            };
            let init_expr = find_expr(class, *init_id).expect("static init");
            if !matches!(
                init_expr.kind,
                ExprKind::Num { .. } | ExprKind::Str(_) | ExprKind::Bool(_)
            ) && !matches!(&init_expr.kind, ExprKind::Unary { op: UnaryOp::Neg, arg } if matches!(arg.kind, ExprKind::Num { .. }))
            {
                return self.err(format!("static field `{sname}` needs a literal value (static state is not supported)"), init_expr.span);
            }
            let (t, value) = if self.is_str(sty) {
                let ExprKind::Str(v) = &init_expr.kind else {
                    unreachable!()
                };
                ("&str".to_string(), string_literal(v))
            } else {
                let x = self.expr(init_expr)?;
                (self.rust_ty(sty, init_expr.span)?, x.code)
            };
            self.line(&format!("pub const {}: {t} = {value};", screaming(sname)));
            first = false;
        }
        for m in &class.members {
            let ClassMember::Method(m) = m else { continue };
            if !first {
                self.blank();
            }
            first = false;
            match m.kind {
                MethodKind::Constructor => self.constructor_item(class, s, m)?,
                _ => self.function_item(&m.func, Some(m))?,
            }
        }
        if s.ctor.is_none() {
            // A class without constructor: `new()` from the field initializers.
            if !first {
                self.blank();
            }
            self.line("pub fn new() -> Self {");
            self.indent += 1;
            self.fns.push(self.plain_ctx(
                class.id,
                Ty::Named(s.name.clone()),
                Some(s.name.clone()),
                true,
            ));
            let fields = self.initial_fields(class, s, &[])?;
            self.fns.pop();
            self.line(&format!("Self {{ {} }}", fields.join(", ")));
            self.indent -= 1;
            self.line("}");
        }
        self.indent -= 1;
        self.line("}");
        Ok(())
    }

    fn plain_ctx(&self, id: NodeId, ret_ty: Ty, class: Option<String>, in_ctor: bool) -> FnGen {
        FnGen {
            id,
            returns_result: false,
            ret_ty,
            targets: Vec::new(),
            try_ctx: Vec::new(),
            in_ctor,
            this_name: if in_ctor { "this" } else { "self" },
            type_params: Vec::new(),
            bounds: Default::default(),
            class,
            labels: 0,
        }
    }

    /// The fields of a new instance from their initializers and parameter properties;
    /// `assigned` gives values for the others (from `this.x = …` in the constructor).
    fn initial_fields(
        &mut self,
        class: &'a Class,
        s: &crate::infer::StructInfo,
        assigned: &[(String, String)],
    ) -> GResult<Vec<String>> {
        let mut out = Vec::new();
        for f in &s.fields {
            let fname = snake(&f.name);
            let ty = if f.optional {
                Ty::Option(Box::new(f.ty.clone()))
            } else {
                f.ty.clone()
            };
            if let Some((_, v)) = assigned.iter().find(|(n, _)| *n == f.name) {
                out.push(if *v == fname {
                    fname
                } else {
                    format!("{fname}: {v}")
                });
                continue;
            }
            let field_ast = class.members.iter().find_map(|m| match m {
                ClassMember::Field(fa) if fa.name == f.name && !fa.is_static => Some(fa),
                _ => None,
            });
            if let Some(fa) = field_ast
                && let Some(init) = &fa.init
            {
                let v = self.expr_to(init, &ty)?;
                out.push(format!("{fname}: {v}"));
                continue;
            }
            if f.optional {
                out.push(format!("{fname}: None"));
                continue;
            }
            let v = self.default_value(&ty, f.span).map_err(|_| {
                crate::error::Error::new(
                    format!("field `{}` of {} is never given a value", f.name, s.name),
                    f.span,
                )
            })?;
            out.push(format!("{fname}: {v}"));
        }
        Ok(out)
    }

    fn constructor_item(
        &mut self,
        class: &'a Class,
        s: &crate::infer::StructInfo,
        m: &'a Method,
    ) -> GResult<()> {
        let f = &m.func;
        let info = self.p.funcs[&f.id].clone();
        self.push_scope();
        self.fns
            .push(self.plain_ctx(f.id, Ty::Named(s.name.clone()), Some(s.name.clone()), true));
        self.fn_ctx_mut().returns_result = info.throws;
        let params = self.param_list(f, &info)?;
        let ret = if info.throws {
            "Result<Self, String>"
        } else {
            "Self"
        };
        let FnBody::Block(body) = &f.body else {
            unreachable!()
        };
        // Parameter properties.
        let mut assigned: Vec<(String, String)> = Vec::new();
        for (i, p) in f.params.iter().enumerate() {
            if p.access.is_some() || p.readonly {
                let Pattern::Ident { name, .. } = &p.pat else {
                    unreachable!()
                };
                let binding = info.params[i];
                let mut x = super::E::atom(self.name(binding), self.repr_of(binding));
                x.var = Some((binding, usize::MAX));
                let pty = self.resolve(&info.sig.params[i]);
                let value = self.coerce(x, &pty, Want::Owned);
                assigned.push((name.clone(), value));
            }
        }
        // `this.x = expr` statements at the start: field values.
        let mut simple = 0;
        for st in &body.stmts {
            let StmtKind::Expr(e) = &st.kind else { break };
            let ExprKind::Assign {
                op: AssignOp::Assign,
                target: AssignTarget::Expr(t),
                value,
            } = &e.kind
            else {
                break;
            };
            let ExprKind::Member { obj, prop, .. } = &t.kind else {
                break;
            };
            if !matches!(obj.kind, ExprKind::This)
                || uses_this(value)
                || assigned.iter().any(|(n, _)| n == prop)
                || s.field(prop).is_none()
            {
                break;
            }
            let field = s.field(prop).expect("field");
            let ty = if field.optional {
                Ty::Option(Box::new(field.ty.clone()))
            } else {
                field.ty.clone()
            };
            let v = self.expr_to(value, &ty)?;
            assigned.push((prop.clone(), v));
            simple += 1;
        }
        let rest = &body.stmts[simple..];
        let fields = self.initial_fields(class, s, &assigned);
        let text = self.capture(|g| {
            g.indent += 1;
            let fields = fields?;
            if rest.is_empty() {
                g.line(&format!(
                    "{}Self {{ {} }}{}",
                    if info.throws { "Ok(" } else { "" },
                    fields.join(", "),
                    if info.throws { ")" } else { "" }
                ));
            } else {
                g.line(&format!("let mut this = Self {{ {} }};", fields.join(", ")));
                g.block_body(rest, false)?;
                g.line(if info.throws { "Ok(this)" } else { "this" });
            }
            g.indent -= 1;
            Ok(())
        });
        self.fns.pop();
        self.pop_scope();
        let text = text?;
        self.line(&format!("pub fn new({params}) -> {ret} {{"));
        self.out.push_str(&text);
        self.line("}");
        Ok(())
    }

    /// The parameter list of a function, binding the parameters.
    fn param_list(&mut self, f: &'a Function, info: &crate::infer::FnInfo) -> GResult<String> {
        let mut params = Vec::new();
        for (i, p) in f.params.iter().enumerate() {
            let binding = info.params[i];
            let var = self.p.var(binding).clone();
            let pty = self.resolve(&info.sig.params[i]);
            let mode = self.param_mode(
                &pty,
                var.stored,
                var.reassigned,
                var.mutated,
                &info.type_params,
            );
            let t = self.mode_ty(&pty, mode, p.span)?;
            let repr = Self::mode_repr(mode);
            let name = self.bind(binding, repr);
            let m = if (var.reassigned
                || (var.mutated && mode == Mode::Value && !self.is_copy(&pty)))
                && mode == Mode::Value
            {
                "mut "
            } else {
                ""
            };
            params.push(format!("{m}{name}: {t}"));
            if !matches!(p.pat, Pattern::Ident { .. }) {
                return self.err(
                    "destructured parameters are not supported yet: destructure in the body",
                    p.span,
                );
            }
        }
        Ok(params.join(", "))
    }

    /// A function or a method.
    pub(super) fn function_item(
        &mut self,
        f: &'a Function,
        method: Option<&'a Method>,
    ) -> GResult<()> {
        let info = self.p.funcs[&f.id].clone();
        let class = info.method_of.clone();
        self.push_scope();
        let ret_ty = self.resolve(&info.sig.ret);
        self.fns.push(FnGen {
            id: f.id,
            returns_result: info.throws,
            ret_ty: ret_ty.clone(),
            targets: Vec::new(),
            try_ctx: Vec::new(),
            in_ctor: false,
            this_name: "self",
            type_params: info.type_params.clone(),
            bounds: Default::default(),
            class: class.clone(),
            labels: 0,
        });
        let params = self.param_list(f, &info);
        let body = self.capture(|g| {
            g.indent += 1;
            match &f.body {
                FnBody::Block(b) => g.block_body(&b.stmts, true)?,
                FnBody::Expr(e) => {
                    let code = g.expr_to(e, &ret_ty)?;
                    let code = if info.throws {
                        format!("Ok({code})")
                    } else {
                        code
                    };
                    g.line(&code);
                }
            }
            g.indent -= 1;
            Ok(())
        });
        let ctx = self.fns.pop().expect("ctx");
        self.pop_scope();
        let params = params?;
        let body = body?;
        let mut generics = Vec::new();
        for tp in &info.type_params {
            match ctx.bounds.get(tp) {
                Some(b) if !b.is_empty() => generics.push(format!(
                    "{tp}: {}",
                    b.iter().copied().collect::<Vec<_>>().join(" + ")
                )),
                _ => generics.push(tp.clone()),
            }
        }
        let generics = if generics.is_empty() {
            String::new()
        } else {
            format!("<{}>", generics.join(", "))
        };
        let ret = self.fn_return_ty(&ret_ty, f.span)?;
        let ret = if info.throws {
            format!(" -> Result<{ret}, String>")
        } else if ret == "()" {
            String::new()
        } else {
            format!(" -> {ret}")
        };
        let (name, self_param, vis) = match method {
            Some(m) => {
                let base = snake(&m.name);
                let name = match m.kind {
                    MethodKind::Set => format!("set_{base}"),
                    _ => base,
                };
                let self_param = if m.is_static {
                    String::new()
                } else if info.mutates_self {
                    "&mut self".to_string()
                } else {
                    "&self".to_string()
                };
                let vis = match m.access {
                    Some(Access::Private) | Some(Access::Protected) => "",
                    _ => "pub ",
                };
                (name, self_param, vis)
            }
            None => (
                snake(f.name.as_deref().unwrap_or("anonymous")),
                String::new(),
                if info.exported { "pub " } else { "" },
            ),
        };
        let all_params = match (self_param.is_empty(), params.is_empty()) {
            (true, _) => params,
            (false, true) => self_param,
            (false, false) => format!("{self_param}, {params}"),
        };
        let asyncness = if info.is_async { "async " } else { "" };
        self.line(&format!(
            "{vis}{asyncness}fn {name}{generics}({all_params}){ret} {{"
        ));
        self.out.push_str(&body);
        self.line("}");
        Ok(())
    }

    fn main_item(&mut self) -> GResult<()> {
        let info = self.p.funcs[&self.p.main_id].clone();
        self.blank();
        self.push_scope();
        self.fns.push(FnGen {
            id: self.p.main_id,
            returns_result: info.throws,
            ret_ty: Ty::Void,
            targets: Vec::new(),
            try_ctx: Vec::new(),
            in_ctor: false,
            this_name: "self",
            type_params: Vec::new(),
            bounds: Default::default(),
            class: None,
            labels: 0,
        });
        let stmts: Vec<&'a Stmt> = self
            .m
            .body
            .iter()
            .filter(|s| {
                !matches!(
                    s.kind,
                    StmtKind::Func(_)
                        | StmtKind::Class(_)
                        | StmtKind::Interface(_)
                        | StmtKind::TypeAlias(_)
                        | StmtKind::Enum(_)
                        | StmtKind::Empty
                        | StmtKind::Import(_)
                        | StmtKind::ExportNames(_)
                )
            })
            .collect();
        let body = self.capture(|g| {
            g.indent += 1;
            for s in &stmts {
                g.stmt(s)?;
            }
            if info.throws {
                g.line("Ok(())");
            }
            g.indent -= 1;
            Ok(())
        });
        self.fns.pop();
        self.pop_scope();
        let body = body?;
        let ret = if info.throws {
            " -> Result<(), String>"
        } else {
            ""
        };
        if info.is_async {
            let h = self.helper(Helper::BlockOn);
            self.line(&format!("fn main(){ret} {{"));
            self.indent += 1;
            self.line(&format!("{h}(async {{"));
            self.out.push_str(&indent_text(&body, 1));
            self.line("})");
            self.indent -= 1;
            self.line("}");
        } else {
            self.line(&format!("fn main(){ret} {{"));
            self.out.push_str(&body);
            self.line("}");
        }
        Ok(())
    }
}

fn format_num(n: f64) -> String {
    if n.fract() == 0.0 {
        format!("{}", n as i64)
    } else {
        format!("{n}")
    }
}

fn uses_this(e: &Expr) -> bool {
    let mut found = false;
    visit_expr(e, &mut |x| {
        if matches!(x.kind, ExprKind::This) {
            found = true;
        }
    });
    found
}

/// Visits every sub-expression.
pub(super) fn visit_expr<'e>(e: &'e Expr, f: &mut dyn FnMut(&'e Expr)) {
    f(e);
    match &e.kind {
        ExprKind::Template { exprs, .. } | ExprKind::Seq(exprs) => {
            exprs.iter().for_each(|x| visit_expr(x, f))
        }
        ExprKind::Array(elems) => {
            for el in elems {
                if let ArrayElem::Expr(x) | ArrayElem::Spread(x) = el {
                    visit_expr(x, f);
                }
            }
        }
        ExprKind::Object(props) => {
            for p in props {
                if let PropValue::Expr(x) | PropValue::Spread(x) = &p.value {
                    visit_expr(x, f);
                }
            }
        }
        ExprKind::Unary { arg, .. } | ExprKind::Update { arg, .. } => visit_expr(arg, f),
        ExprKind::Binary { left, right, .. } | ExprKind::Logical { left, right, .. } => {
            visit_expr(left, f);
            visit_expr(right, f);
        }
        ExprKind::Assign { target, value, .. } => {
            if let AssignTarget::Expr(t) = target {
                visit_expr(t, f);
            }
            visit_expr(value, f);
        }
        ExprKind::Cond { test, cons, alt } => {
            visit_expr(test, f);
            visit_expr(cons, f);
            visit_expr(alt, f);
        }
        ExprKind::Call { callee, args, .. } | ExprKind::New { callee, args, .. } => {
            visit_expr(callee, f);
            args.iter().for_each(|a| visit_expr(&a.expr, f));
        }
        ExprKind::Member { obj, .. } => visit_expr(obj, f),
        ExprKind::Index { obj, index, .. } => {
            visit_expr(obj, f);
            visit_expr(index, f);
        }
        ExprKind::As(x, _)
        | ExprKind::NonNull(x)
        | ExprKind::TypeOf(x)
        | ExprKind::Void(x)
        | ExprKind::Delete(x)
        | ExprKind::Await(x) => visit_expr(x, f),
        ExprKind::Arrow(func) | ExprKind::Func(func) => {
            if let FnBody::Expr(x) = &func.body {
                visit_expr(x, f);
            }
        }
        _ => {}
    }
}

/// The expression with the given id inside a class (static field initializers).
fn find_expr(class: &Class, id: NodeId) -> Option<&Expr> {
    for m in &class.members {
        if let ClassMember::Field(f) = m
            && let Some(init) = &f.init
            && init.id == id
        {
            return Some(init);
        }
    }
    None
}

fn indent_text(text: &str, levels: usize) -> String {
    let pad = "    ".repeat(levels);
    text.lines()
        .map(|l| {
            if l.is_empty() {
                String::new()
            } else {
                format!("{pad}{l}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
        + "\n"
}

