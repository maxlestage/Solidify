//! Module-level items: constants, enums, structs, implementations, functions, `main`.

use super::{
    Bounds, FnGen, GResult, Gen, Helper, Mode, Repr, Want, pascal, screaming, snake, string_literal,
};
use crate::ast::*;
use crate::infer::{Callee, EnumKind, EnumValue, Role, StructKind};
use crate::types::Ty;
use std::collections::HashMap;

impl<'a> Gen<'a> {
    pub(super) fn module(&mut self) -> GResult<String> {
        let mut header = String::new();
        if !self.opts.no_header {
            let imported: Vec<&str> = self
                .opts
                .files
                .iter()
                .filter(|f| !f.is_entry)
                .map(|f| f.name.as_str())
                .collect();
            let from = self
                .opts
                .file_name
                .as_deref()
                .map_or(String::new(), |f| format!(" from {f}"));
            let from = if imported.is_empty() {
                from
            } else {
                format!("{from} and {}", imported.join(", "))
            };
            header.push_str(&format!(
                "// Generated by Solidify{from}: TypeScript in, Rust out.\n"
            ));
            header.push_str("// https://github.com/maxlestage/Solidify\n\n");
        }
        // Items are written into the buffer; `use` lines and helpers are decided after.
        let files = self.opts.files.clone();
        let multi = files.len() > 1;
        let mut sections: Vec<String> = Vec::new();
        if multi {
            for (i, f) in files.iter().enumerate() {
                self.in_module = !f.is_entry;
                let text = self.capture(|g| g.items_of(Some(i)));
                self.in_module = false;
                sections.push(text?);
            }
        } else {
            self.items_of(None)?;
        }
        if self.p.has_main {
            self.main_item()?;
        }
        let body = std::mem::take(&mut self.out);
        let mut out = header;
        if !self.p.has_main {
            out.push_str("#![allow(dead_code)]\n\n");
        }
        let mut uses: Vec<&str> = Vec::new();
        if self.uses_rc {
            uses.push("use std::cell::RefCell;");
        }
        if self.uses_rc {
            uses.push("use std::rc::Rc;");
        }
        match (self.uses_lazy, self.uses_mutex) {
            (true, true) => uses.push("use std::sync::{LazyLock, Mutex};"),
            (true, false) => uses.push("use std::sync::LazyLock;"),
            _ => {}
        }
        if !uses.is_empty() {
            out.push_str(&uses.join("\n"));
            out.push('\n');
            if !(self.uses_hashmap || self.uses_hashset) {
                out.push('\n');
            }
        }
        if self.uses_hashmap && self.uses_hashset {
            out.push_str("use std::collections::{HashMap, HashSet};\n\n");
        } else if self.uses_hashmap {
            out.push_str("use std::collections::HashMap;\n\n");
        } else if self.uses_hashset {
            out.push_str("use std::collections::HashSet;\n\n");
        }
        if !multi {
            out.push_str(body.trim_start_matches('\n'));
            let (before, after) = self.impls_of(None)?;
            out.push_str(&before);
            self.helper_sources(&mut out);
            out.push_str(&after);
            return Ok(out);
        }
        // Each imported file is a module; implementations stay with their types, so that
        // private fields stay private.
        let mut impls = Vec::new();
        for i in 0..files.len() {
            impls.push(self.impls_of(Some(i))?);
        }
        for (i, f) in files.iter().enumerate() {
            if f.is_entry {
                continue;
            }
            let (before, after) = &impls[i];
            let inner = format!("{}{before}{after}", sections[i]);
            if inner.trim().is_empty() {
                // Only re-exports: nothing to hold.
                continue;
            }
            out.push_str(&format!("mod {} {{\n    use super::*;\n\n", f.module));
            out.push_str(&indent_text(inner.trim_start_matches('\n'), 1));
            out.push_str(&format!("}}\n\npub use {}::*;\n\n", f.module));
        }
        let entry = files.iter().position(|f| f.is_entry).unwrap_or(0);
        let (before, after) = &impls[entry];
        let mut tail = format!("{}{body}{before}", sections[entry]);
        self.helper_sources(&mut tail);
        tail.push_str(after);
        out.push_str(tail.trim_start_matches('\n'));
        Ok(out)
    }

    /// The items declared in one file (`None`: in the whole program).
    fn items_of(&mut self, file: Option<usize>) -> GResult<()> {
        self.consts(file)?;
        for en in &self.p.enums.clone() {
            if self.owned_by(en.span, file) {
                self.enum_item(en)?;
            }
        }
        for u in &self.p.unions.clone() {
            if self.owned_by(u.span, file) {
                self.union_item(u)?;
            }
        }
        for s in &self.p.structs.clone() {
            if self.owned_by(s.span, file) && !self.abstract_iface(&s.name) {
                self.struct_item(s)?;
            }
        }
        for s in &self.m.body {
            if let StmtKind::Func(f) = &s.kind
                && f.id != usize::MAX
                && self.owned_by(s.span, file)
            {
                self.blank();
                for c in &s.comments {
                    self.line(&format!("/// {c}"));
                }
                self.function_item(f, None, None)?;
            }
        }
        Ok(())
    }

    /// The implementations for the types of one file: those written before the runtime
    /// helpers (accessors, traits) and those after (`JsInspect`, `JsFromJson`).
    fn impls_of(&mut self, file: Option<usize>) -> GResult<(String, String)> {
        let mut before = self.union_impls(file)?;
        before.push_str(&self.trait_items(file)?);
        let mut after = String::new();
        let generic = file.is_none_or(|i| self.opts.files[i].is_entry);
        for (owner, text) in self.inspect_impls()?.into_iter().chain(self.json_impls()?) {
            let wanted = match owner {
                None => generic,
                Some(name) => file.is_none_or(|i| self.type_file(&name) == i),
            };
            if wanted {
                after.push_str(&text);
            }
        }
        Ok((before, after))
    }

    fn helper_sources(&self, out: &mut String) {
        let mut helpers = self.helpers.clone();
        // Showing values prints numbers.
        if helpers.contains(&Helper::Inspect) || helpers.contains(&Helper::Json) {
            helpers.insert(Helper::NumText);
        }
        for h in helpers {
            out.push('\n');
            out.push_str(h.source());
            out.push('\n');
        }
    }

    /// `JsInspect` for the structs and enums that `console.log` shows: the generic
    /// implementations (owner `None`), then one text per type.
    fn inspect_impls(&mut self) -> GResult<Vec<(Option<String>, String)>> {
        let mut items = Vec::new();
        let mut out = String::new();
        if !self.helpers.contains(&Helper::Inspect) {
            return Ok(items);
        }
        // A type parameter shown: any type of the program may be shown through it.
        if self.generic_inspect {
            let names: Vec<String> = self
                .p
                .structs
                .iter()
                .map(|s| s.name.clone())
                .chain(self.p.enums.iter().map(|e| e.name.clone()))
                .chain(self.p.unions.iter().map(|u| u.name.clone()))
                .collect();
            for n in names {
                self.mark_inspected(&Ty::named(n));
            }
        }
        if self.helpers.contains(&Helper::JsMap) {
            out.push_str(
                "\nimpl<K: JsInspect + std::hash::Hash + Eq + Clone, V: JsInspect> JsInspect for JsMap<K, V> {\n    fn js_value(&self) -> JsValue {\n        JsValue::Map(self.iter().map(|(k, v)| (k.js_value(), v.js_value())).collect())\n    }\n}\n",
            );
        }
        if self.helpers.contains(&Helper::JsSet) {
            out.push_str(
                "\nimpl<T: JsInspect + std::hash::Hash + Eq + Clone> JsInspect for JsSet<T> {\n    fn js_value(&self) -> JsValue {\n        JsValue::Set(self.iter().map(JsInspect::js_value).collect())\n    }\n}\n",
            );
        }
        if self.helpers.contains(&Helper::Date) {
            out.push_str(
                "\nimpl JsInspect for JsDate {\n    fn js_value(&self) -> JsValue {\n        JsValue::Date(self.to_iso_string(), self.to_string())\n    }\n}\n",
            );
        }
        if self.helpers.contains(&Helper::Regex) {
            out.push_str(
                "\nimpl JsInspect for JsRegex {\n    fn js_value(&self) -> JsValue {\n        JsValue::Raw(self.to_string())\n    }\n}\n\nimpl JsInspect for JsMatch {\n    fn js_value(&self) -> JsValue {\n        JsValue::Array(self.groups.iter().map(|g| g.as_ref().map_or(JsValue::Undefined, |s| JsValue::Str(s.clone()))).collect())\n    }\n}\n",
            );
        }
        items.push((None, std::mem::take(&mut out)));
        // Fields may bring in more types: loop until the set is stable.
        let mut done = std::collections::BTreeSet::new();
        loop {
            let pending: Vec<String> = self
                .inspected
                .iter()
                .filter(|n| !done.contains(*n))
                .cloned()
                .collect();
            if pending.is_empty() {
                break;
            }
            for name in pending {
                done.insert(name.clone());
                let params = self
                    .p
                    .struct_info(&name)
                    .map(|s| s.type_params.clone())
                    .unwrap_or_default();
                let prev = std::mem::replace(&mut self.class_params, params.clone());
                let header = self.generic_header(&params, &["JsInspect"]);
                let rust_name = pascal(&name);
                let args = if params.is_empty() {
                    String::new()
                } else {
                    format!("<{}>", params.join(", "))
                };
                out.push_str(&format!(
                    "\nimpl{header} JsInspect for {rust_name}{args} {{\n    fn js_value(&self) -> JsValue {{\n"
                ));
                if let Some(u) = self.p.union_info(&name).cloned() {
                    out.push_str("        match self {\n");
                    for m in &u.members {
                        let inner = self.js_value_of("v", &m.ty);
                        out.push_str(&format!(
                            "            {rust_name}::{}(v) => {inner},\n",
                            m.name
                        ));
                    }
                    out.push_str("        }\n");
                } else if let Some(en) = self.p.enum_info(&name).cloned() {
                    if en.kind == EnumKind::Numeric {
                        out.push_str("        match self {\n");
                        for v in &en.variants {
                            let value = match &v.value {
                                Some(EnumValue::Num(n)) if n.fract() == 0.0 => {
                                    format!("JsValue::Int({})", *n as i64)
                                }
                                Some(EnumValue::Num(n)) => format!("JsValue::Float({n:?})"),
                                _ => "JsValue::Str(self.to_string())".to_string(),
                            };
                            out.push_str(&format!(
                                "            {rust_name}::{} => {value},\n",
                                v.name
                            ));
                        }
                        out.push_str("        }\n");
                    } else {
                        out.push_str("        JsValue::Str(self.to_string())\n");
                    }
                } else if let Some(info) = self.p.struct_info(&name).cloned() {
                    let class = if info.kind == StructKind::Class {
                        format!("Some({})", string_literal(&name))
                    } else {
                        "None".to_string()
                    };
                    // Each field in its place; an optional field of an object literal
                    // is there only when given.
                    let mut parts: Vec<(String, Option<(String, String)>)> = Vec::new();
                    for f in &info.fields {
                        let key = string_literal(&f.name);
                        let field = snake(&f.name);
                        let undefined = self
                            .p
                            .undef_fields
                            .contains(&(name.clone(), f.name.clone()));
                        let value = match self.resolve(&f.ty) {
                            Ty::Func(_) => format!("JsValue::Func({key})"),
                            _ if f.optional && info.kind == StructKind::Class => {
                                // A declared class field exists, `undefined` until set.
                                let inner = self.js_value_of("v", &f.ty);
                                format!(
                                    "self.{field}.as_ref().map_or(JsValue::Undefined, |v| {inner})"
                                )
                            }
                            _ if f.optional => {
                                let inner = self.js_value_of("v", &f.ty);
                                parts.push((key, Some((field, inner))));
                                continue;
                            }
                            Ty::Option(inner_ty) if undefined => {
                                let inner = self.js_value_of("v", &inner_ty);
                                format!(
                                    "self.{field}.as_ref().map_or(JsValue::Undefined, |v| {inner})"
                                )
                            }
                            _ => self.js_value_of(&format!("self.{field}"), &f.ty),
                        };
                        parts.push((format!("({key}.to_string(), {value})"), None));
                    }
                    if parts.iter().all(|(_, o)| o.is_none()) {
                        let entries: Vec<String> = parts.into_iter().map(|(e, _)| e).collect();
                        out.push_str(&format!(
                            "        JsValue::Object({class}, vec![{}])\n",
                            entries.join(", ")
                        ));
                    } else {
                        out.push_str(
                            "        let mut props: Vec<(String, JsValue)> = Vec::new();\n",
                        );
                        for (entry, optional) in parts {
                            match optional {
                                None => out.push_str(&format!("        props.push({entry});\n")),
                                Some((field, inner)) => out.push_str(&format!(
                                    "        if let Some(v) = &self.{field} {{\n            props.push(({entry}.to_string(), {inner}));\n        }}\n"
                                )),
                            }
                        }
                        out.push_str(&format!("        JsValue::Object({class}, props)\n"));
                    }
                }
                out.push_str("    }\n}\n");
                self.class_params = prev;
                items.push((Some(name.clone()), std::mem::take(&mut out)));
            }
        }
        Ok(items)
    }

    /// `JsFromJson` for the types `JSON.parse` builds, like [`Self::inspect_impls`].
    fn json_impls(&mut self) -> GResult<Vec<(Option<String>, String)>> {
        let mut items = Vec::new();
        let mut out = String::new();
        if !self.helpers.contains(&Helper::Json) {
            return Ok(items);
        }
        if self.helpers.contains(&Helper::JsMap) {
            out.push_str(
                "\nimpl<V: JsFromJson> JsFromJson for JsMap<String, V> {\n    fn from_json(v: &JsonValue) -> Result<Self, String> {\n        let mut out = JsMap::new();\n        for (k, x) in v.object(\"an object\")? {\n            out.insert(k.clone(), V::from_json(x).map_err(|e| format!(\"{e} (in \\\"{k}\\\")\"))?);\n        }\n        Ok(out)\n    }\n}\n",
            );
        }
        items.push((None, std::mem::take(&mut out)));
        for name in self.json_types.clone() {
            let rust_name = pascal(&name);
            let name_lit = string_literal(&name);
            let params = self
                .p
                .struct_info(&name)
                .map(|s| s.type_params.clone())
                .unwrap_or_default();
            let header = self.generic_header(&params, &["JsFromJson"]);
            let args = if params.is_empty() {
                String::new()
            } else {
                format!("<{}>", params.join(", "))
            };
            out.push_str(&format!(
                "\nimpl{header} JsFromJson for {rust_name}{args} {{\n    fn from_json(v: &JsonValue) -> Result<Self, String> {{\n"
            ));
            if let Some(u) = self.p.union_info(&name).cloned() {
                if let Some(d) = &u.discriminant {
                    let d_lit = string_literal(d);
                    out.push_str(&format!(
                        "        let o = v.object({name_lit})?;\n        match JsonValue::get(o, {d_lit}) {{\n            Some(JsonValue::Str(tag)) => match tag.as_str() {{\n"
                    ));
                    for m in &u.members {
                        let Some(tag) = &m.tag else { continue };
                        let t = self.rust_ty(&m.ty, u.span)?;
                        out.push_str(&format!(
                            "                {} => Ok({rust_name}::{}(<{t}>::from_json(v)?)),\n",
                            string_literal(tag),
                            m.name
                        ));
                    }
                    out.push_str(&format!(
                        "                _ => Err(format!(\"JSON: {{tag:?}} is not a {d} of {name}\")),\n            }},\n            _ => Err(\"JSON: a {name} needs a string field {d}\".to_string()),\n        }}\n"
                    ));
                } else {
                    // Each member by the kind of JSON value it is; objects are tried in order.
                    let mut arms: Vec<(&str, Vec<String>)> = Vec::new();
                    for m in &u.members {
                        let kind = match self.resolve(&m.ty) {
                            Ty::Str => "JsonValue::Str(_)",
                            Ty::Num(_) => "JsonValue::Num(_)",
                            Ty::Bool => "JsonValue::Bool(_)",
                            Ty::Null | Ty::Void => "JsonValue::Null",
                            Ty::Array(_) | Ty::Tuple(_) => "JsonValue::Array(_)",
                            _ => "JsonValue::Object(_)",
                        };
                        let t = self.rust_ty(&m.ty, u.span)?;
                        let read = format!("<{t}>::from_json(v).map({rust_name}::{})", m.name);
                        match arms.iter_mut().find(|(k, _)| *k == kind) {
                            Some((_, reads)) => reads.push(read),
                            None => arms.push((kind, vec![read])),
                        }
                    }
                    out.push_str("        match v {\n");
                    for (kind, reads) in arms {
                        let mut chain = reads[0].clone();
                        for r in &reads[1..] {
                            chain = format!("{chain}.or_else(|_| {r})");
                        }
                        out.push_str(&format!("            {kind} => {chain},\n"));
                    }
                    out.push_str(&format!(
                        "            other => Err(format!(\"JSON: expected a {name}, got {{}}\", other.kind())),\n        }}\n"
                    ));
                }
            } else if let Some(en) = self.p.enum_info(&name).cloned() {
                if en.kind == EnumKind::Numeric {
                    out.push_str("        let JsonValue::Num(n) = v else {\n");
                    out.push_str(&format!(
                        "            return Err(format!(\"JSON: expected a number for {name}, got {{}}\", v.kind()));\n        }};\n"
                    ));
                    for v in &en.variants {
                        let Some(EnumValue::Num(n)) = &v.value else {
                            continue;
                        };
                        let lit = if n.fract() == 0.0 {
                            format!("{}.0", *n as i64)
                        } else {
                            format!("{n:?}")
                        };
                        out.push_str(&format!(
                            "        if *n == {lit} {{\n            return Ok({rust_name}::{});\n        }}\n",
                            v.name
                        ));
                    }
                    out.push_str(&format!(
                        "        Err(format!(\"JSON: {{}} is not a value of {name}\", js_number_text(*n)))\n"
                    ));
                } else {
                    out.push_str(
                        "        match v {\n            JsonValue::Str(s) => match s.as_str() {\n",
                    );
                    for v in &en.variants {
                        let text = match &v.value {
                            Some(EnumValue::Str(s)) => s.clone(),
                            Some(EnumValue::Num(n)) => format_num(*n),
                            None => v.source.clone(),
                        };
                        out.push_str(&format!(
                            "                {} => Ok({rust_name}::{}),\n",
                            string_literal(&text),
                            v.name
                        ));
                    }
                    out.push_str(&format!(
                        "                _ => Err(format!(\"JSON: {{s:?}} is not a value of {name}\")),\n            }},\n            other => Err(format!(\"JSON: expected a string for {name}, got {{}}\", other.kind())),\n        }}\n"
                    ));
                }
            } else if let Some(info) = self.p.struct_info(&name).cloned() {
                out.push_str(&format!(
                    "        let o = v.object({name_lit})?;\n        Ok({rust_name} {{\n"
                ));
                for f in &info.fields {
                    out.push_str(&format!(
                        "            {}: js_json_field(o, {})?,\n",
                        snake(&f.name),
                        string_literal(&f.name)
                    ));
                }
                out.push_str("        })\n");
            }
            out.push_str("    }\n}\n");
            items.push((Some(name.clone()), std::mem::take(&mut out)));
        }
        Ok(items)
    }

    /// Top-level `const`s holding literals.
    fn consts(&mut self, file: Option<usize>) -> GResult<()> {
        let mut written = false;
        for s in &self.m.body {
            let StmtKind::Var(v) = &s.kind else { continue };
            if !self.owned_by(s.span, file) {
                continue;
            }
            for d in &v.decls {
                let Pattern::Ident { id, span, .. } = &d.pat else {
                    continue;
                };
                let var = self.p.var(*id).clone();
                // A top-level variable used inside a function: a static, lazily made.
                if !var.const_literal && var.role == Role::TopLevel && var.used_in_fn {
                    let Some(init) = &d.init else {
                        return self.err(
                            format!("the top-level variable `{}` is used inside a function: give it a value where it is declared", var.name),
                            *span,
                        );
                    };
                    let ty = self.resolve(&var.ty);
                    let mutable = var.reassigned || var.mutated;
                    let name = screaming(&var.name);
                    self.names.insert(*id, name.clone());
                    self.reprs.insert(*id, Repr::Owned);
                    self.statics.insert(*id, mutable);
                    self.uses_lazy = true;
                    self.fns.push(self.plain_ctx(*id, ty.clone(), None, false));
                    let value = self.expr_to(init, &ty);
                    self.fns.pop();
                    let value = value?;
                    let t = self.rust_ty(&ty, *span)?;
                    let vis = self.vis(v.exported);
                    for c in &s.comments {
                        self.line(&format!("/// {c}"));
                    }
                    if mutable {
                        self.uses_mutex = true;
                        self.line(&format!(
                            "{vis}static {name}: LazyLock<Mutex<{t}>> = LazyLock::new(|| Mutex::new({value}));"
                        ));
                    } else {
                        self.line(&format!(
                            "{vis}static {name}: LazyLock<{t}> = LazyLock::new(|| {value});"
                        ));
                    }
                    written = true;
                    continue;
                }
                if !var.const_literal {
                    continue;
                }
                let init = d.init.as_ref().expect("literal");
                let ty = self.resolve(&var.ty);
                let name = self.bind(
                    *id,
                    if self.is_str(&ty) {
                        Repr::Str
                    } else {
                        Repr::Owned
                    },
                );
                let (t, value) = if self.is_str(&ty) {
                    let ExprKind::Str(s) = &init.kind else {
                        unreachable!()
                    };
                    ("&str".to_string(), string_literal(s))
                } else {
                    let x = self.expr(init)?;
                    (self.rust_ty(&ty, *span)?, x.code)
                };
                let vis = self.vis(v.exported);
                for c in &s.comments {
                    self.line(&format!("/// {c}"));
                }
                self.line(&format!("{vis}const {name}: {t} = {value};"));
                written = true;
            }
        }
        if written {
            self.blank();
        }
        Ok(())
    }

    fn enum_item(&mut self, en: &crate::infer::EnumInfo) -> GResult<()> {
        self.blank();
        let name = pascal(&en.name);
        let vis = self.vis(en.exported);
        self.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
        self.line(&format!("{vis}enum {name} {{"));
        self.indent += 1;
        for v in &en.variants {
            self.line(&format!("{},", v.name));
        }
        self.indent -= 1;
        self.line("}");
        self.blank();
        // Printing gives the JavaScript value.
        self.line(&format!("impl std::fmt::Display for {name} {{"));
        self.indent += 1;
        self.line("fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {");
        self.indent += 1;
        self.line("f.write_str(match self {");
        self.indent += 1;
        for v in &en.variants {
            let text = match (&v.value, en.kind) {
                (Some(EnumValue::Str(s)), _) => string_literal(s),
                (Some(EnumValue::Num(n)), _) => string_literal(&format_num(*n)),
                (None, EnumKind::Literals) => string_literal(&v.source),
                (None, _) => string_literal(&v.source),
            };
            self.line(&format!("{name}::{} => {text},", v.name));
        }
        self.indent -= 1;
        self.line("})");
        self.indent -= 1;
        self.line("}");
        self.indent -= 1;
        self.line("}");
        if self.p.enum_names.contains(&en.name) {
            // `Level[x]`: from a value back to the member's name.
            self.blank();
            self.line(&format!("impl {name} {{"));
            self.indent += 1;
            self.line("/// `Level[Level.High]`: the member's name.");
            self.line("#[allow(dead_code)]");
            self.line("fn name(&self) -> &'static str {");
            self.indent += 1;
            self.line("match self {");
            self.indent += 1;
            for v in &en.variants {
                self.line(&format!(
                    "{name}::{} => {},",
                    v.name,
                    string_literal(&v.source)
                ));
            }
            self.indent -= 1;
            self.line("}");
            self.indent -= 1;
            self.line("}");
            self.blank();
            self.line(
                "/// `Level[2]`: the name of the member with this value, `undefined` if none.",
            );
            self.line("#[allow(dead_code)]");
            self.line("fn name_of(value: f64) -> &'static str {");
            self.indent += 1;
            let pairs: Vec<String> = en
                .variants
                .iter()
                .map(|v| {
                    let n = match &v.value {
                        Some(EnumValue::Num(n)) => *n,
                        _ => 0.0,
                    };
                    format!("({n:?}, {})", string_literal(&v.source))
                })
                .collect();
            self.line(&format!("[{}]", pairs.join(", ")));
            self.indent += 1;
            self.line(".iter()");
            self.line(".find(|(v, _)| *v == value)");
            self.line(".map_or(\"undefined\", |(_, n)| *n)");
            self.indent -= 2;
            self.line("}");
            self.indent -= 1;
            self.line("}");
        }
        Ok(())
    }

    /// The enum of a union of different types.
    fn union_item(&mut self, u: &crate::infer::UnionInfo) -> GResult<()> {
        self.blank();
        let name = pascal(&u.name);
        let vis = self.vis(u.exported);
        for c in u.members.iter().map(|m| m.name.clone()).take(0) {
            let _ = c;
        }
        self.line("#[derive(Debug, Clone, PartialEq)]");
        self.line(&format!("{vis}enum {name} {{"));
        self.indent += 1;
        for m in &u.members {
            let t = self.rust_ty(&m.ty, u.span)?;
            self.line(&format!("{}({t}),", m.name));
        }
        self.indent -= 1;
        self.line("}");
        Ok(())
    }

    /// Accessors of the fields read on union values, and `js_typeof`.
    fn union_impls(&mut self, file: Option<usize>) -> GResult<String> {
        let mut out = String::new();
        for u in self.p.unions.clone() {
            if !self.owned_by(u.span, file) {
                continue;
            }
            let name = pascal(&u.name);
            let accessors: Vec<(String, bool)> = self
                .union_accessors
                .iter()
                .filter(|(en, _, _)| *en == u.name)
                .map(|(_, f, m)| (f.clone(), *m))
                .collect();
            let typeof_wanted = self.union_typeof.contains(&u.name);
            if accessors.is_empty() && !typeof_wanted {
                continue;
            }
            out.push_str(&format!("\nimpl {name} {{\n"));
            let mut first = true;
            let mut done = std::collections::BTreeSet::new();
            for (field, mutable) in accessors {
                for m in [false, mutable] {
                    if !done.insert((field.clone(), m)) {
                        continue;
                    }
                    if !first {
                        out.push('\n');
                    }
                    first = false;
                    let fty = u
                        .members
                        .first()
                        .and_then(|member| match self.resolve(&member.ty) {
                            Ty::Named(n, ..) => self.p.struct_info(&n).and_then(|s| {
                                s.field(&field).map(|f| {
                                    if f.optional {
                                        Ty::Option(Box::new(f.ty.clone()))
                                    } else {
                                        f.ty.clone()
                                    }
                                })
                            }),
                            _ => None,
                        })
                        .unwrap_or(Ty::Any);
                    let t = self.rust_ty(&fty, u.span)?;
                    let f = snake(&field);
                    let (suffix, amp, selfp) = if m {
                        ("_mut", "&mut ", "&mut self")
                    } else {
                        ("", "&", "&self")
                    };
                    out.push_str(&format!(
                        "    fn {f}{suffix}({selfp}) -> {amp}{t} {{\n        match self {{\n"
                    ));
                    for member in &u.members {
                        out.push_str(&format!(
                            "            {name}::{}(v) => {amp}v.{f},\n",
                            member.name
                        ));
                    }
                    out.push_str("        }\n    }\n");
                }
            }
            if typeof_wanted {
                if !first {
                    out.push('\n');
                }
                out.push_str("    fn js_typeof(&self) -> &'static str {\n        match self {\n");
                for member in &u.members {
                    let word = match self.resolve(&member.ty) {
                        Ty::Num(_) => "number",
                        Ty::Str => "string",
                        Ty::Bool => "boolean",
                        Ty::Func(_) => "function",
                        _ => "object",
                    };
                    out.push_str(&format!(
                        "            {name}::{}(_) => \"{word}\",\n",
                        member.name
                    ));
                }
                out.push_str("        }\n    }\n");
            }
            out.push_str("}\n");
        }
        Ok(out)
    }

    fn struct_item(&mut self, s: &crate::infer::StructInfo) -> GResult<()> {
        self.blank();
        let name = pascal(&s.name);
        let vis = self.vis(s.exported || s.kind == StructKind::Synth);
        // A `dyn` value cannot be compared; a function cannot be shown or compared.
        let has_fn = s
            .fields
            .iter()
            .any(|f| matches!(self.resolve(&f.ty), Ty::Func(_)));
        if has_fn {
            self.line("#[derive(Clone)]");
        } else if s.fields.iter().any(|f| self.contains_dyn(&f.ty)) {
            self.line("#[derive(Debug, Clone)]");
        } else {
            self.line("#[derive(Debug, Clone, PartialEq)]");
        }
        let params = s.type_params.clone();
        let generics = if params.is_empty() {
            String::new()
        } else {
            format!("<{}>", params.join(", "))
        };
        let prev_params = std::mem::replace(&mut self.class_params, params.clone());
        let given = self.ancestor_subst(&s.name);
        let prev_subst = std::mem::replace(&mut self.class_subst, given);
        let mut bounds = Bounds::new();
        for (p, c) in &s.type_bounds {
            bounds
                .entry(p.clone())
                .or_default()
                .insert(Self::bound_trait(c));
        }
        let prev_bounds = std::mem::replace(&mut self.class_bounds, bounds);
        let r = self.struct_body(s, &name, vis, has_fn, &generics);
        self.class_subst = prev_subst;
        self.class_params = prev_params;
        self.class_bounds = prev_bounds;
        r
    }

    fn struct_body(
        &mut self,
        s: &crate::infer::StructInfo,
        name: &str,
        vis: &str,
        has_fn: bool,
        generics: &str,
    ) -> GResult<()> {
        self.line(&format!("{vis}struct {name}{generics} {{"));
        self.indent += 1;
        for f in &s.fields {
            let ty = if f.optional {
                Ty::Option(Box::new(f.ty.clone()))
            } else {
                f.ty.clone()
            };
            let t = self.rust_ty(&ty, f.span)?;
            let fvis = match f.access {
                Some(Access::Private) | Some(Access::Protected) => "",
                _ => "pub ",
            };
            self.line(&format!("{fvis}{}: {t},", snake(&f.name)));
        }
        self.indent -= 1;
        self.line("}");
        if has_fn {
            // `Debug` by hand: the functions are shown as such.
            self.blank();
            let header = self.generic_header(&s.type_params, &["std::fmt::Debug"]);
            self.line(&format!(
                "impl{header} std::fmt::Debug for {name}{generics} {{"
            ));
            self.indent += 1;
            self.line("fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {");
            self.indent += 1;
            self.line(&format!("f.debug_struct({})", string_literal(name)));
            self.indent += 1;
            for f in &s.fields {
                let fname = snake(&f.name);
                if matches!(self.resolve(&f.ty), Ty::Func(_)) {
                    self.line(&format!(
                        ".field({}, &\"[Function]\")",
                        string_literal(&fname)
                    ));
                } else {
                    self.line(&format!(
                        ".field({}, &self.{fname})",
                        string_literal(&fname)
                    ));
                }
            }
            self.line(".finish()");
            self.indent -= 2;
            self.line("}");
            self.indent -= 1;
            self.line("}");
        }
        if s.kind != StructKind::Class {
            return Ok(());
        }
        let class = self.class_asts.get(&s.name).copied().expect("class ast");
        // The methods written for this class: its own, then the inherited ones it does
        // not override (abstract classes only get their constructor and statics).
        let mut methods: Vec<(String, &'a Method)> = Vec::new();
        let mut seen: Vec<(String, MethodKind)> = Vec::new();
        if !s.is_abstract {
            for owner in self.p.ancestry(&s.name) {
                let Some(ast) = self.class_asts.get(&owner).copied() else {
                    continue;
                };
                for m in &ast.members {
                    let ClassMember::Method(m) = m else { continue };
                    if m.kind == MethodKind::Constructor
                        || (m.is_static && owner != s.name)
                        || seen.contains(&(m.name.clone(), m.kind))
                    {
                        continue;
                    }
                    seen.push((m.name.clone(), m.kind));
                    if !m.is_abstract {
                        methods.push((owner.clone(), m));
                    }
                }
            }
        }
        let inherited_ctor = if s.ctor.is_none() {
            self.p.ancestry(&s.name)[1..].iter().find_map(|c| {
                self.p
                    .struct_info(c)
                    .and_then(|si| si.ctor.map(|id| (c.clone(), id)))
            })
        } else {
            None
        };
        self.current_class = Some(s.name.clone());
        self.blank();
        // The bounds of a generic struct's `impl` are known once its methods are written:
        // the header is completed then.
        let header_at = self.out.len();
        self.line(&format!("impl {name}{generics} {{"));
        self.indent += 1;
        // A generic class keeps its statics in an `impl` of its own (`Name<()>`): a call
        // like `Name::of(…)` could not tell the type arguments of the generic one.
        let generic = !s.type_params.is_empty();
        let statics_text = self.capture(|g| g.static_consts(class, s))?;
        if !generic && !statics_text.is_empty() {
            self.out.push_str(&statics_text);
            self.blank();
        }
        if let Some(m) = class.members.iter().find_map(|m| match m {
            ClassMember::Method(m) if m.kind == MethodKind::Constructor => Some(m),
            _ => None,
        }) {
            self.constructor_item(class, s, m)?;
        } else if let Some((owner, ctor)) = inherited_ctor {
            self.inherited_constructor(class, s, &owner, ctor)?;
        } else {
            // A class without constructor: `new()` from the field initializers.
            self.line("pub fn new() -> Self {");
            self.indent += 1;
            self.fns.push(self.plain_ctx(
                class.id,
                Ty::named(s.name.clone()),
                Some(s.name.clone()),
                true,
            ));
            let fields = self.initial_fields(class, s, &[])?;
            self.fns.pop();
            self.line(&format!("Self {{ {} }}", fields.join(", ")));
            self.indent -= 1;
            self.line("}");
        }
        let mut statics = Vec::new();
        for (_, m) in methods {
            if generic && m.is_static {
                statics.push(m);
                continue;
            }
            self.blank();
            self.function_item(&m.func, Some(m), None)?;
        }
        // `super.m()`: the base class's version, as `base_m`, possibly needing more.
        let mut written: std::collections::BTreeSet<(String, String)> = Default::default();
        loop {
            let pending: Vec<(String, String)> = self
                .super_helpers
                .get(&s.name)
                .map(|set| {
                    set.iter()
                        .filter(|h| !written.contains(*h))
                        .cloned()
                        .collect()
                })
                .unwrap_or_default();
            if pending.is_empty() {
                break;
            }
            for (owner, method) in pending {
                written.insert((owner.clone(), method.clone()));
                let Some(ast) = self.class_asts.get(&owner).copied() else {
                    continue;
                };
                let Some(m) = ast.members.iter().find_map(|m| match m {
                    ClassMember::Method(m) if m.name == method && m.kind == MethodKind::Method => {
                        Some(m)
                    }
                    _ => None,
                }) else {
                    continue;
                };
                self.blank();
                let helper = format!("{}_{}", snake(&owner), snake(&method));
                self.function_item(&m.func, Some(m), Some(&helper))?;
            }
        }
        self.indent -= 1;
        self.line("}");
        self.current_class = None;
        if !s.type_params.is_empty() {
            self.found_bounds
                .insert(format!("struct:{}", s.name), self.class_bounds.clone());
            let header = self.generic_header(&s.type_params, &["Clone"]);
            let at = header_at + self.out[header_at..].find("impl ").expect("impl header");
            self.out.replace_range(at..at + 4, &format!("impl{header}"));
            if !statics_text.is_empty() || !statics.is_empty() {
                let unit = vec!["()"; s.type_params.len()].join(", ");
                self.blank();
                self.line(&format!("impl {name}<{unit}> {{"));
                self.indent += 1;
                self.out.push_str(&statics_text);
                for m in statics {
                    self.blank();
                    self.function_item(&m.func, Some(m), None)?;
                }
                self.indent -= 1;
                self.line("}");
            }
        }
        Ok(())
    }

    /// The `const`s of a class's static fields.
    fn static_consts(&mut self, class: &'a Class, s: &crate::infer::StructInfo) -> GResult<()> {
        for (sname, sty, init) in &s.statics {
            let Some(init_id) = init else {
                return self.err(
                    format!("static field `{sname}` needs a literal value"),
                    s.span,
                );
            };
            let init_expr = find_expr(class, *init_id).expect("static init");
            if !matches!(
                init_expr.kind,
                ExprKind::Num { .. } | ExprKind::Str(_) | ExprKind::Bool(_)
            ) && !matches!(&init_expr.kind, ExprKind::Unary { op: UnaryOp::Neg, arg } if matches!(arg.kind, ExprKind::Num { .. }))
            {
                return self.err(format!("static field `{sname}` needs a literal value (static state is not supported)"), init_expr.span);
            }
            let (t, value) = if self.is_str(sty) {
                let ExprKind::Str(v) = &init_expr.kind else {
                    unreachable!()
                };
                ("&str".to_string(), string_literal(v))
            } else {
                let x = self.expr(init_expr)?;
                (self.rust_ty(sty, init_expr.span)?, x.code)
            };
            self.line(&format!("pub const {}: {t} = {value};", screaming(sname)));
        }
        Ok(())
    }

    /// The constructor a class gets from its base class: the same parameters, the base
    /// part built first.
    fn inherited_constructor(
        &mut self,
        class: &'a Class,
        s: &crate::infer::StructInfo,
        owner: &str,
        ctor: NodeId,
    ) -> GResult<()> {
        let f = self.fn_asts.get(&ctor).copied().expect("ctor ast");
        let info = self.p.funcs[&ctor].clone();
        self.push_scope();
        self.fns
            .push(self.plain_ctx(f.id, Ty::named(s.name.clone()), Some(s.name.clone()), true));
        self.fn_ctx_mut().returns_result = info.throws;
        let params = self.param_list(f, &info)?;
        let names: Vec<String> = info.params.iter().map(|b| self.name(*b)).collect();
        let call = format!(
            "{}::new({}){}",
            pascal(owner),
            names.join(", "),
            if info.throws { "?" } else { "" }
        );
        let parent = s.parent.clone().expect("parent");
        let assigned = self.base_fields(&parent);
        let fields = self.initial_fields(class, s, &assigned);
        self.fns.pop();
        self.pop_scope();
        let fields = fields?;
        let ret = if info.throws {
            "Result<Self, String>"
        } else {
            "Self"
        };
        self.line(&format!("pub fn new({params}) -> {ret} {{"));
        self.indent += 1;
        self.line(&format!("let base = {call};"));
        self.line(&format!(
            "{}Self {{ {} }}{}",
            if info.throws { "Ok(" } else { "" },
            fields.join(", "),
            if info.throws { ")" } else { "" }
        ));
        self.indent -= 1;
        self.line("}");
        Ok(())
    }

    /// The fields of the base class, taken from `base`.
    fn base_fields(&self, parent: &str) -> Vec<(String, String)> {
        self.p
            .struct_info(parent)
            .map(|p| {
                p.fields
                    .iter()
                    .map(|f| (f.name.clone(), format!("base.{}", snake(&f.name))))
                    .collect()
            })
            .unwrap_or_default()
    }

    fn plain_ctx(&self, id: NodeId, ret_ty: Ty, class: Option<String>, in_ctor: bool) -> FnGen {
        FnGen {
            id,
            returns_result: false,
            ret_ty,
            yield_ty: None,
            targets: Vec::new(),
            try_ctx: Vec::new(),
            in_ctor,
            this_name: if in_ctor { "this" } else { "self" },
            type_params: Vec::new(),
            bounds: Default::default(),
            class,
            labels: 0,
        }
    }

    /// The fields of a new instance from their initializers and parameter properties;
    /// `assigned` gives values for the others (from `this.x = …` in the constructor).
    fn initial_fields(
        &mut self,
        class: &'a Class,
        s: &crate::infer::StructInfo,
        assigned: &[(String, String)],
    ) -> GResult<Vec<String>> {
        let mut out = Vec::new();
        for f in &s.fields {
            let fname = snake(&f.name);
            let ty = if f.optional {
                Ty::Option(Box::new(f.ty.clone()))
            } else {
                f.ty.clone()
            };
            if let Some((_, v)) = assigned.iter().find(|(n, _)| *n == f.name) {
                out.push(if *v == fname {
                    fname
                } else {
                    format!("{fname}: {v}")
                });
                continue;
            }
            let field_ast = class.members.iter().find_map(|m| match m {
                ClassMember::Field(fa) if fa.name == f.name && !fa.is_static => Some(fa),
                _ => None,
            });
            if let Some(fa) = field_ast
                && let Some(init) = &fa.init
            {
                let v = self.expr_to(init, &ty)?;
                out.push(format!("{fname}: {v}"));
                continue;
            }
            if f.optional {
                out.push(format!("{fname}: None"));
                continue;
            }
            let v = self.default_value(&ty, f.span).map_err(|_| {
                crate::error::Error::new(
                    format!("field `{}` of {} is never given a value", f.name, s.name),
                    f.span,
                )
            })?;
            out.push(format!("{fname}: {v}"));
        }
        Ok(out)
    }

    fn constructor_item(
        &mut self,
        class: &'a Class,
        s: &crate::infer::StructInfo,
        m: &'a Method,
    ) -> GResult<()> {
        let f = &m.func;
        let info = self.p.funcs[&f.id].clone();
        self.push_scope();
        self.fns
            .push(self.plain_ctx(f.id, Ty::named(s.name.clone()), Some(s.name.clone()), true));
        self.fn_ctx_mut().returns_result = info.throws;
        let params = self.param_list(f, &info)?;
        let ret = if info.throws {
            "Result<Self, String>"
        } else {
            "Self"
        };
        let FnBody::Block(body) = &f.body else {
            unreachable!()
        };
        // `super(args)`: the base part is built first.
        let mut prelude: Vec<String> = Vec::new();
        let mut super_at = None;
        for (i, st) in body.stmts.iter().enumerate() {
            if let StmtKind::Expr(x) = &st.kind
                && let ExprKind::Call { callee, args, .. } = &x.kind
                && matches!(callee.kind, ExprKind::Super)
            {
                let owner = match self.p.calls.get(&x.id) {
                    Some(Callee::SuperCtor(owner)) => owner.clone(),
                    _ => s.parent.clone().unwrap_or_default(),
                };
                let call = match self.p.struct_info(&owner).and_then(|o| o.ctor) {
                    Some(ctor) => {
                        let pf = self.p.funcs[&ctor].clone();
                        let list = self.user_args(&pf, args, x.span)?;
                        format!(
                            "{}::new({list}){}",
                            pascal(&owner),
                            if pf.throws { "?" } else { "" }
                        )
                    }
                    None => format!("{}::new()", pascal(&owner)),
                };
                prelude.push(format!("let base = {call};"));
                super_at = Some(i);
                break;
            }
        }
        let lead: &[Stmt] = match super_at {
            Some(i) => &body.stmts[..i],
            None => &[],
        };
        let stmts: &[Stmt] = match super_at {
            Some(i) => &body.stmts[i + 1..],
            None => &body.stmts,
        };
        // Parameter properties.
        let mut assigned: Vec<(String, String)> = Vec::new();
        for (i, p) in f.params.iter().enumerate() {
            if p.access.is_some() || p.readonly {
                let Pattern::Ident { name, .. } = &p.pat else {
                    unreachable!()
                };
                let binding = info.params[i];
                let mut x = super::E::atom(self.name(binding), self.repr_of(binding));
                x.var = Some((binding, usize::MAX));
                let pty = self.resolve(&info.sig.params[i]);
                let value = self.coerce(x, &pty, Want::Owned);
                assigned.push((name.clone(), value));
            }
        }
        // `this.x = expr` statements at the start: field values.
        let mut simple = 0;
        for st in stmts {
            let StmtKind::Expr(e) = &st.kind else { break };
            let ExprKind::Assign {
                op: AssignOp::Assign,
                target: AssignTarget::Expr(t),
                value,
            } = &e.kind
            else {
                break;
            };
            let ExprKind::Member { obj, prop, .. } = &t.kind else {
                break;
            };
            if !matches!(obj.kind, ExprKind::This)
                || uses_this(value)
                || assigned.iter().any(|(n, _)| n == prop)
                || s.field(prop).is_none()
            {
                break;
            }
            let field = s.field(prop).expect("field");
            let ty = if field.optional {
                Ty::Option(Box::new(field.ty.clone()))
            } else {
                field.ty.clone()
            };
            let v = self.expr_to(value, &ty)?;
            assigned.push((prop.clone(), v));
            simple += 1;
        }
        let rest = &stmts[simple..];
        if super_at.is_some()
            && let Some(parent) = &s.parent
        {
            for (fname, value) in self.base_fields(parent) {
                if !assigned.iter().any(|(n, _)| *n == fname) {
                    assigned.push((fname, value));
                }
            }
        }
        let fields = self.initial_fields(class, s, &assigned);
        let text = self.capture(|g| {
            g.indent += 1;
            for st in lead {
                g.stmt(st)?;
            }
            for p in &prelude {
                g.line(p);
            }
            let fields = fields?;
            if rest.is_empty() {
                g.line(&format!(
                    "{}Self {{ {} }}{}",
                    if info.throws { "Ok(" } else { "" },
                    fields.join(", "),
                    if info.throws { ")" } else { "" }
                ));
            } else {
                g.line(&format!("let mut this = Self {{ {} }};", fields.join(", ")));
                g.block_body(rest, false)?;
                g.line(if info.throws { "Ok(this)" } else { "this" });
            }
            g.indent -= 1;
            Ok(())
        });
        self.fns.pop();
        self.pop_scope();
        let text = text?;
        self.line(&format!("pub fn new({params}) -> {ret} {{"));
        self.out.push_str(&text);
        self.line("}");
        Ok(())
    }

    /// The parameter list of a function, binding the parameters.
    fn param_list(&mut self, f: &'a Function, info: &crate::infer::FnInfo) -> GResult<String> {
        let mut params = Vec::new();
        for (i, p) in f.params.iter().enumerate() {
            let binding = info.params[i];
            let var = self.p.var(binding).clone();
            let pty = self.resolve(&info.sig.params[i]);
            let all_params = self.all_type_params(info);
            let mode = self.param_mode(
                &info.sig.params[i],
                var.stored || var.shared,
                var.reassigned,
                var.mutated,
                &all_params,
            );
            let t = self.mode_ty(&pty, mode, p.span)?;
            let repr = Self::mode_repr(mode);
            let name = self.bind(binding, repr);
            if var.shared {
                self.shared.insert(binding);
                self.uses_rc = true;
                self.param_rebinds
                    .push(format!("let {name} = Rc::new(RefCell::new({name}));"));
            }
            let m = if (var.reassigned
                || (var.mutated && mode == Mode::Value && !self.is_copy(&pty)))
                && mode == Mode::Value
            {
                "mut "
            } else {
                ""
            };
            params.push(format!("{m}{name}: {t}"));
            // `{ x, y }: Point`: the parameter is taken whole, then taken apart.
            if !matches!(p.pat, Pattern::Ident { .. }) {
                let lines = self.capture(|g| match &p.pat {
                    Pattern::Object { props, .. } => g.destructure_object(props, &name, &pty),
                    Pattern::Array { elems, rest, .. } => {
                        g.destructure_array(elems, rest, &name, &pty)
                    }
                    Pattern::Ident { .. } => Ok(()),
                })?;
                for l in lines.lines().map(str::trim).filter(|l| !l.is_empty()) {
                    self.param_rebinds.push(l.to_string());
                }
            }
        }
        Ok(params.join(", "))
    }

    /// A function or a method (`rename` gives a method another name: the base class's
    /// version written for a subclass).
    pub(super) fn function_item(
        &mut self,
        f: &'a Function,
        method: Option<&'a Method>,
        rename: Option<&str>,
    ) -> GResult<()> {
        let info = self.p.funcs[&f.id].clone();
        let class = self
            .current_class
            .clone()
            .or_else(|| info.method_of.clone());
        self.push_scope();
        let ret_ty = self.resolve(&info.sig.ret);
        self.fns.push(FnGen {
            id: f.id,
            returns_result: info.throws,
            ret_ty: ret_ty.clone(),
            yield_ty: match (f.is_generator, &ret_ty) {
                (true, Ty::Gen(t)) => Some((**t).clone()),
                _ => None,
            },
            targets: Vec::new(),
            try_ctx: Vec::new(),
            in_ctor: false,
            this_name: "self",
            type_params: info.type_params.clone(),
            bounds: Default::default(),
            class: class.clone(),
            labels: 0,
        });
        let params = self.param_list(f, &info);
        if f.is_generator {
            // The body yields through `y`, on its own thread.
            self.fn_ctx_mut().returns_result = false;
            self.fn_ctx_mut().ret_ty = Ty::Void;
        }
        let rebinds = std::mem::take(&mut self.param_rebinds);
        let body = self.capture(|g| {
            g.indent += 1;
            for r in &rebinds {
                g.line(r);
            }
            if f.is_generator {
                let FnBody::Block(b) = &f.body else {
                    unreachable!()
                };
                let gen_name = g.helper(Helper::Generator);
                g.line(&format!("{gen_name}::new(move |y| {{"));
                g.indent += 1;
                g.block_body(&b.stmts, false)?;
                g.indent -= 1;
                g.line("})");
                g.indent -= 1;
                return Ok(());
            }
            match &f.body {
                FnBody::Block(b) => g.block_body(&b.stmts, true)?,
                FnBody::Expr(e) => {
                    let code = g.expr_to(e, &ret_ty)?;
                    let code = if info.throws {
                        format!("Ok({code})")
                    } else {
                        code
                    };
                    g.line(&code);
                }
            }
            g.indent -= 1;
            Ok(())
        });
        let ctx = self.fns.pop().expect("ctx");
        self.pop_scope();
        let params = params?;
        let body = body?;
        if !info.type_params.is_empty() {
            let own: Bounds = ctx
                .bounds
                .iter()
                .filter(|(k, _)| info.type_params.contains(k))
                .map(|(k, v)| (k.clone(), v.clone()))
                .collect();
            self.found_bounds
                .entry(format!("fn:{}", info.id))
                .or_default()
                .extend(own);
        }
        let mut generics = Vec::new();
        let mut ctx = ctx;
        // Every value of the program can be copied (`Clone`): the parameters too.
        for tp in &info.type_params {
            ctx.bounds.entry(tp.clone()).or_default().insert("Clone");
        }
        for (p, c) in &info.type_bounds {
            ctx.bounds
                .entry(p.clone())
                .or_default()
                .insert(Self::bound_trait(c));
        }
        for tp in &info.type_params {
            match ctx.bounds.get(tp) {
                Some(b) if !b.is_empty() => generics.push(format!(
                    "{tp}: {}",
                    b.iter().copied().collect::<Vec<_>>().join(" + ")
                )),
                _ => generics.push(tp.clone()),
            }
        }
        let generics = if generics.is_empty() {
            String::new()
        } else {
            format!("<{}>", generics.join(", "))
        };
        let mut ret = self.fn_return_ty(&ret_ty, f.span)?;
        if method.is_some() && self.fluent(&info) {
            ret = if self.p.method_mutates(info.id) {
                "&mut Self".into()
            } else {
                "&Self".into()
            };
        }
        let ret = if info.throws && !f.is_generator {
            format!(" -> Result<{ret}, String>")
        } else if ret == "()" {
            String::new()
        } else {
            format!(" -> {ret}")
        };
        let (name, self_param, vis) = match method {
            Some(m) => {
                let base = snake(&m.name);
                let name = match (rename, m.kind) {
                    (Some(r), _) => r.to_string(),
                    (None, MethodKind::Set) => format!("set_{base}"),
                    _ => base,
                };
                let self_param = if m.is_static {
                    String::new()
                } else if info.mutates_self {
                    "&mut self".to_string()
                } else {
                    "&self".to_string()
                };
                let vis = match m.access {
                    Some(Access::Private) | Some(Access::Protected) => "",
                    _ => "pub ",
                };
                (name, self_param, vis)
            }
            None => (
                snake(f.name.as_deref().unwrap_or("anonymous")),
                String::new(),
                self.vis(info.exported),
            ),
        };
        let all_params = match (self_param.is_empty(), params.is_empty()) {
            (true, _) => params,
            (false, true) => self_param,
            (false, false) => format!("{self_param}, {params}"),
        };
        let asyncness = if info.is_async { "async " } else { "" };
        self.line(&format!(
            "{vis}{asyncness}fn {name}{generics}({all_params}){ret} {{"
        ));
        self.out.push_str(&body);
        self.line("}");
        Ok(())
    }

    /// The signature of a method as a trait wants it, and its parameter names.
    fn method_sig(&mut self, m: &'a Method, mutable: bool) -> GResult<(String, Vec<String>)> {
        let info = self.p.funcs[&m.func.id].clone();
        self.push_scope();
        self.fns.push(self.plain_ctx(
            m.func.id,
            info.sig.ret.clone(),
            info.method_of.clone(),
            false,
        ));
        let params = self.param_list(&m.func, &info);
        let names: Vec<String> = info.params.iter().map(|b| self.name(*b)).collect();
        let ret_ty = self.resolve(&info.sig.ret);
        let ret = self.fn_return_ty(&ret_ty, m.span);
        self.fns.pop();
        self.pop_scope();
        let (params, ret) = (params?, ret?);
        let ret = if info.throws {
            format!(" -> Result<{ret}, String>")
        } else if ret == "()" {
            String::new()
        } else {
            format!(" -> {ret}")
        };
        let name = match m.kind {
            MethodKind::Set => format!("set_{}", snake(&m.name)),
            _ => snake(&m.name),
        };
        let self_param = if mutable { "&mut self" } else { "&self" };
        let all = if params.is_empty() {
            self_param.to_string()
        } else {
            format!("{self_param}, {params}")
        };
        Ok((format!("fn {name}({all}){ret}"), names))
    }

    /// The methods a class answers to, its own first: (declaring class, method).
    fn class_methods(&self, class: &str) -> Vec<(String, &'a Method)> {
        let mut out = Vec::new();
        let mut seen: Vec<(String, MethodKind)> = Vec::new();
        for owner in self.p.ancestry(class) {
            let Some(ast) = self.class_asts.get(&owner).copied() else {
                continue;
            };
            for m in &ast.members {
                let ClassMember::Method(m) = m else { continue };
                if m.kind == MethodKind::Constructor
                    || m.is_static
                    || seen.contains(&(m.name.clone(), m.kind))
                {
                    continue;
                }
                seen.push((m.name.clone(), m.kind));
                out.push((owner.clone(), m));
            }
        }
        out
    }

    /// A trait per base class held dynamically, with the accessors of its fields and its
    /// methods, implemented by the class and every subclass.
    fn trait_items(&mut self, file: Option<usize>) -> GResult<String> {
        let mut bases: Vec<String> = self.p.polymorphic.iter().cloned().collect();
        bases.sort();
        let inspect = self.helpers.contains(&Helper::Inspect);
        let mut out = String::new();
        for base in bases {
            let Some(info) = self.p.struct_info(&base).cloned() else {
                continue;
            };
            if !self.owned_by(info.span, file) {
                continue;
            }
            let name = pascal(&base);
            let trait_name = format!("{name}Like");
            let ancestry = self.p.ancestry(&base);
            let parent_dyn = ancestry[1..].iter().find(|a| self.p.is_dyn(a)).cloned();
            let mut supers = vec!["std::fmt::Debug".to_string()];
            if inspect {
                supers.push("JsInspect".into());
            }
            if let Some(p) = &parent_dyn {
                supers.push(format!("{}Like", pascal(p)));
            }
            // What the base trait already declares is not declared again.
            let (parent_fields, parent_methods): (Vec<String>, Vec<(String, MethodKind)>) =
                match &parent_dyn {
                    Some(p) => (
                        self.p
                            .struct_info(p)
                            .map(|s| s.fields.iter().map(|f| f.name.clone()).collect())
                            .unwrap_or_default(),
                        self.class_methods(p)
                            .iter()
                            .map(|(_, m)| (m.name.clone(), m.kind))
                            .collect(),
                    ),
                    None => (Vec::new(), Vec::new()),
                };
            let fields: Vec<crate::infer::FieldInfo> = info
                .fields
                .iter()
                .filter(|f| !parent_fields.contains(&f.name))
                .cloned()
                .collect();
            // An interface has no bodies: its methods are those of the first class
            // implementing it (the others have the same signatures).
            let iface = info.kind == StructKind::Interface;
            let methods: Vec<(String, &'a Method)> = if iface {
                let first = self
                    .p
                    .descendants(&base)
                    .into_iter()
                    .find(|c| self.p.struct_info(c).is_some_and(|s| !s.is_abstract));
                match first {
                    Some(c) => self
                        .class_methods(&c)
                        .into_iter()
                        .filter(|(_, m)| info.method(&m.name, m.kind).is_some())
                        .collect(),
                    None => Vec::new(),
                }
            } else {
                self.class_methods(&base)
                    .into_iter()
                    .filter(|(_, m)| {
                        !parent_methods.contains(&(m.name.clone(), m.kind))
                            && m.func.type_params.is_empty()
                    })
                    .collect()
            };
            let tests: Vec<(String, bool)> = self
                .instance_tests
                .iter()
                .filter(|(b, _, _)| *b == base)
                .map(|(_, sub, m)| (sub.clone(), *m))
                .collect();
            // A generic base: `trait ContainerLike<T>`, implemented with the arguments
            // each class gives (`impl ContainerLike<i64> for Cell`).
            let params = info.type_params.clone();
            let generics = if params.is_empty() {
                String::new()
            } else {
                format!("<{}>", params.join(", "))
            };
            let prev_params = std::mem::replace(&mut self.class_params, params.clone());
            // The trait.
            let mut lines: Vec<String> = Vec::new();
            for f in &fields {
                let ty = if f.optional {
                    Ty::Option(Box::new(f.ty.clone()))
                } else {
                    f.ty.clone()
                };
                let t = self.rust_ty(&ty, f.span)?;
                let fname = snake(&f.name);
                lines.push(format!("    fn {fname}(&self) -> &{t};"));
                if self.dyn_setters.contains(&(base.clone(), f.name.clone())) {
                    lines.push(format!("    fn {fname}_mut(&mut self) -> &mut {t};"));
                }
            }
            // Each method with the types of the base (an interface's own, with its
            // parameters), as the calls through the trait pass the arguments.
            let mut sigs: Vec<(&'a Method, NodeId, bool)> = Vec::new();
            for (_, m) in &methods {
                let trait_fn = if iface {
                    match info.method(&m.name, m.kind) {
                        Some(im) => im.fn_id,
                        None => continue,
                    }
                } else {
                    m.func.id
                };
                let mutable = self.p.method_mutates(m.func.id) || self.p.method_mutates(trait_fn);
                let sig = self.trait_sig(m, trait_fn, mutable)?;
                lines.push(format!("    {};", sig.text(&[])));
                sigs.push((m, trait_fn, mutable));
            }
            for (sub, mutable) in &tests {
                let target = if self.p.is_dyn(sub) {
                    format!("dyn {}Like", pascal(sub))
                } else {
                    pascal(sub)
                };
                lines.push(format!(
                    "    fn as_{}(&self) -> Option<&{target}>;",
                    snake(sub)
                ));
                if *mutable {
                    lines.push(format!(
                        "    fn as_{}_mut(&mut self) -> Option<&mut {target}>;",
                        snake(sub)
                    ));
                }
            }
            let clone_name = format!("clone_{}", snake(&base));
            lines.push(format!(
                "    fn {clone_name}(&self) -> Box<dyn {trait_name}{generics}>;"
            ));
            self.class_params = prev_params;
            out.push_str(&format!(
                "\n/// `{base}`{}.\ntrait {trait_name}{generics}: {} {{\n{}\n}}\n",
                if iface {
                    " and the classes implementing it"
                } else {
                    " and its subclasses"
                },
                supers.join(" + "),
                lines.join("\n")
            ));
            out.push_str(&format!(
                "\nimpl{generics} Clone for Box<dyn {trait_name}{generics}> {{\n    fn clone(&self) -> Self {{\n        self.{clone_name}()\n    }}\n}}\n"
            ));
            // The implementations: the base itself (unless it is an interface with
            // methods, which no value is of) and what descends from or implements it.
            let mut classes: Vec<String> = if self.abstract_iface(&base) {
                Vec::new()
            } else {
                vec![base.clone()]
            };
            classes.extend(self.p.descendants(&base));
            let order: Vec<String> = self.p.structs.iter().map(|s| s.name.clone()).collect();
            classes.sort_by_key(|c| order.iter().position(|o| o == c));
            for c in classes {
                let Some(cinfo) = self.p.struct_info(&c).cloned() else {
                    continue;
                };
                if cinfo.is_abstract {
                    continue;
                }
                // The base's parameters as this class gives them.
                let given = self.base_args(&c, &base, iface);
                let own = cinfo.type_params.clone();
                let prev_subst = std::mem::replace(&mut self.class_subst, given.clone());
                let prev_params = std::mem::replace(&mut self.class_params, own.clone());
                let prev_class = self.current_class.replace(c.clone());
                let r = self.dyn_impl(
                    &c,
                    &base,
                    &trait_name,
                    &params,
                    &fields,
                    &sigs,
                    &tests,
                    &clone_name,
                );
                self.class_subst = prev_subst;
                self.class_params = prev_params;
                self.current_class = prev_class;
                out.push_str(&r?);
                if inspect {
                    self.mark_inspected(&Ty::named(c.clone()));
                }
            }
        }
        out.push_str(&self.bound_trait_items(file)?);
        Ok(out)
    }

    /// The signature of a method of a `dyn` trait: the types of `trait_fn` (the base
    /// class's method, or the interface's, with its parameters), passed as the calls
    /// through the trait pass them; `m` gives the names.
    fn trait_sig(&mut self, m: &'a Method, trait_fn: NodeId, mutable: bool) -> GResult<TraitSig> {
        let info = self.p.funcs[&trait_fn].clone();
        let own = self.p.funcs[&m.func.id].clone();
        let bindings = if info.params.len() == info.sig.params.len() {
            info.params.clone()
        } else {
            own.params.clone()
        };
        let all = self.all_type_params(&info);
        let mut params = Vec::new();
        for (i, b) in bindings.iter().enumerate() {
            let var = self.p.var(*b).clone();
            let pt = info.sig.params[i].clone();
            let mode = self.param_mode(
                &pt,
                var.stored || var.shared,
                var.reassigned,
                var.mutated,
                &all,
            );
            let pty = self.resolve(&pt);
            let t = self.mode_ty(&pty, mode, m.span)?;
            params.push((snake(&var.name), t, mode, pty));
        }
        let ret_ty = self.resolve(&info.sig.ret);
        let ret = self.fn_return_ty(&ret_ty, m.span)?;
        let ret = if info.throws || own.throws {
            format!(" -> Result<{ret}, String>")
        } else if ret == "()" {
            String::new()
        } else {
            format!(" -> {ret}")
        };
        let name = match m.kind {
            MethodKind::Set => format!("set_{}", snake(&m.name)),
            _ => snake(&m.name),
        };
        Ok(TraitSig {
            name,
            self_param: if mutable { "&mut self" } else { "&self" },
            params,
            ret,
        })
    }

    /// How a method passes each parameter.
    fn param_modes(&self, info: &crate::infer::FnInfo) -> Vec<Mode> {
        let all = self.all_type_params(info);
        info.params
            .iter()
            .zip(&info.sig.params)
            .map(|(b, pt)| {
                let var = self.p.var(*b);
                self.param_mode(
                    pt,
                    var.stored || var.shared,
                    var.reassigned,
                    var.mutated,
                    &all,
                )
            })
            .collect()
    }

    /// The parameters of `base` (a generic class or interface held as `dyn`) as class
    /// `c` gives them.
    fn base_args(&self, c: &str, base: &str, iface: bool) -> HashMap<String, Ty> {
        let Some(b) = self.p.struct_info(base) else {
            return HashMap::new();
        };
        if b.type_params.is_empty() || c == base {
            return HashMap::new();
        }
        if iface {
            let args = self
                .p
                .ancestry(c)
                .iter()
                .filter_map(|a| self.p.struct_info(a))
                .find_map(|s| {
                    s.implements_args
                        .iter()
                        .find(|(i, _)| i == base)
                        .map(|(_, a)| a.clone())
                })
                .unwrap_or_default();
            return b.type_params.iter().cloned().zip(args).collect();
        }
        let all = self.ancestor_subst(c);
        b.type_params
            .iter()
            .filter_map(|p| all.get(p).map(|t| (p.clone(), t.clone())))
            .collect()
    }

    /// `impl BaseLike<…> for C`: the accessors, the methods (calling the class's own,
    /// each argument passed as it wants), the type tests and the copy.
    #[allow(clippy::too_many_arguments)]
    fn dyn_impl(
        &mut self,
        c: &str,
        base: &str,
        trait_name: &str,
        params: &[String],
        fields: &[crate::infer::FieldInfo],
        sigs: &[(&'a Method, NodeId, bool)],
        tests: &[(String, bool)],
        clone_name: &str,
    ) -> GResult<String> {
        let cname = pascal(c);
        let own = self
            .p
            .struct_info(c)
            .map(|s| s.type_params.clone())
            .unwrap_or_default();
        let span = self.p.struct_info(c).map(|s| s.span).unwrap_or_default();
        let trait_args = if params.is_empty() {
            String::new()
        } else {
            let mut parts = Vec::new();
            for p in params {
                parts.push(self.rust_ty(&Ty::named(p.clone()), span)?);
            }
            format!("<{}>", parts.join(", "))
        };
        let (impl_generics, c_generics) = if own.is_empty() {
            (String::new(), String::new())
        } else {
            let inspect = self.helpers.contains(&Helper::Inspect);
            let known = self
                .known_bounds
                .get(&format!("struct:{c}"))
                .cloned()
                .unwrap_or_default();
            let list: Vec<String> = own
                .iter()
                .map(|p| {
                    let mut b: std::collections::BTreeSet<&str> =
                        ["Clone", "std::fmt::Debug", "'static"]
                            .into_iter()
                            .collect();
                    if inspect {
                        b.insert("JsInspect");
                    }
                    if let Some(more) = known.get(p) {
                        b.extend(more.iter().copied());
                    }
                    format!("{p}: {}", b.into_iter().collect::<Vec<_>>().join(" + "))
                })
                .collect();
            (
                format!("<{}>", list.join(", ")),
                format!("<{}>", own.join(", ")),
            )
        };
        let mut body: Vec<String> = Vec::new();
        for f in fields {
            let ty = if f.optional {
                Ty::Option(Box::new(f.ty.clone()))
            } else {
                f.ty.clone()
            };
            let t = self.rust_ty(&ty, f.span)?;
            let fname = snake(&f.name);
            body.push(format!(
                "    fn {fname}(&self) -> &{t} {{\n        &self.{fname}\n    }}"
            ));
            if self
                .dyn_setters
                .contains(&(base.to_string(), f.name.clone()))
            {
                body.push(format!(
                    "    fn {fname}_mut(&mut self) -> &mut {t} {{\n        &mut self.{fname}\n    }}"
                ));
            }
        }
        for (m, trait_fn, mutable) in sigs {
            let sig = self.trait_sig(m, *trait_fn, *mutable)?;
            let Some((_, cm)) = self
                .class_methods(c)
                .into_iter()
                .find(|(_, x)| x.name == m.name && x.kind == m.kind)
            else {
                continue;
            };
            let target = self.p.funcs[&cm.func.id].clone();
            let wanted = self.param_modes(&target);
            let mut args = vec!["self".to_string()];
            let mut muts = Vec::new();
            for (i, (name, _, mode, ty)) in sig.params.iter().enumerate() {
                let to = wanted.get(i).copied().unwrap_or(*mode);
                let (code, needs_mut) = self.adapt_arg(name, *mode, to, ty);
                args.push(code);
                muts.push(needs_mut);
            }
            body.push(format!(
                "    {} {{\n        {cname}::{}({})\n    }}",
                sig.text(&muts),
                sig.name,
                args.join(", ")
            ));
        }
        for (sub, mutable) in tests {
            let target = if self.p.is_dyn(sub) {
                format!("dyn {}Like", pascal(sub))
            } else {
                pascal(sub)
            };
            let is = self.p.is_subclass(c, sub);
            body.push(format!(
                "    fn as_{}(&self) -> Option<&{target}> {{\n        {}\n    }}",
                snake(sub),
                if is { "Some(self)" } else { "None" }
            ));
            if *mutable {
                body.push(format!(
                    "    fn as_{}_mut(&mut self) -> Option<&mut {target}> {{\n        {}\n    }}",
                    snake(sub),
                    if is { "Some(self)" } else { "None" }
                ));
            }
        }
        body.push(format!(
            "    fn {clone_name}(&self) -> Box<dyn {trait_name}{trait_args}> {{\n        Box::new(self.clone())\n    }}"
        ));
        Ok(format!(
            "\nimpl{impl_generics} {trait_name}{trait_args} for {cname}{c_generics} {{\n{}\n}}\n",
            body.join("\n\n")
        ))
    }

    /// An argument received as `from` and passed on as `to` (`&x`, `x.clone()`…); and
    /// whether the parameter must be `mut`.
    fn adapt_arg(&self, name: &str, from: Mode, to: Mode, ty: &Ty) -> (String, bool) {
        let copy = self.is_copy(ty);
        let str_inner = matches!(self.resolve(ty), Ty::Option(ref i) if self.is_str(i));
        let code = match (from, to) {
            (a, b) if a == b => name.to_string(),
            (Mode::Value, Mode::Ref | Mode::Slice | Mode::StrRef) => format!("&{name}"),
            (Mode::Value, Mode::RefMut) => return (format!("&mut {name}"), true),
            (Mode::Value, Mode::OptRef) if str_inner => format!("{name}.as_deref()"),
            (Mode::Value, Mode::OptRef) => format!("{name}.as_ref()"),
            (Mode::Ref | Mode::RefMut, Mode::Value) if copy => format!("*{name}"),
            (Mode::Ref | Mode::RefMut, Mode::Value) => format!("{name}.clone()"),
            (Mode::StrRef, Mode::Value) => format!("{name}.to_string()"),
            (Mode::Slice, Mode::Value) => format!("{name}.to_vec()"),
            (Mode::OptRef, Mode::Value) if str_inner => format!("{name}.map(str::to_string)"),
            (Mode::OptRef, Mode::Value) => format!("{name}.cloned()"),
            (Mode::StrRef, Mode::Ref) => format!("&{name}.to_string()"),
            (Mode::Slice, Mode::Ref) => format!("&{name}.to_vec()"),
            _ => name.to_string(),
        };
        (code, false)
    }

    /// The traits of the constraints (`T extends HasId` → `trait HasIdLike`): an accessor
    /// per field and the methods, implemented by every type given for such a parameter.
    fn bound_trait_items(&mut self, file: Option<usize>) -> GResult<String> {
        let constraints: std::collections::BTreeSet<String> = self
            .p
            .funcs
            .values()
            .flat_map(|f| f.type_bounds.iter().map(|(_, c)| c.clone()))
            .chain(
                self.p
                    .structs
                    .iter()
                    .flat_map(|s| s.type_bounds.iter().map(|(_, c)| c.clone())),
            )
            .collect();
        let mut out = String::new();
        for c in constraints {
            // A class held as `dyn` already has its trait, implemented by its subclasses.
            if self.p.is_dyn(&c) {
                continue;
            }
            let Some(info) = self.p.struct_info(&c).cloned() else {
                continue;
            };
            if !self.owned_by(info.span, file) {
                continue;
            }
            let trait_name = Self::bound_trait(&c);
            let impls: Vec<String> = self
                .p
                .bound_impls
                .iter()
                .filter(|(k, _)| *k == c)
                .map(|(_, n)| n.clone())
                .collect();
            let mut lines = Vec::new();
            let mut getters = Vec::new();
            for f in &info.fields {
                let ty = if f.optional {
                    Ty::Option(Box::new(f.ty.clone()))
                } else {
                    f.ty.clone()
                };
                let t = self.rust_ty(&ty, f.span)?;
                let fname = snake(&f.name);
                let setter = self.bound_setters.contains(&(c.clone(), f.name.clone()));
                lines.push(format!("    fn {fname}(&self) -> &{t};"));
                if setter {
                    lines.push(format!("    fn {fname}_mut(&mut self) -> &mut {t};"));
                }
                getters.push((fname, t, setter));
            }
            // The methods, with the signatures of a class that has them.
            let mut sigs: Vec<(String, Vec<String>)> = Vec::new();
            for mi in &info.methods {
                let candidates: Vec<String> = std::iter::once(c.clone())
                    .chain(impls.iter().cloned())
                    .collect();
                let found = candidates.iter().find_map(|k| {
                    self.class_methods(k)
                        .into_iter()
                        .find(|(_, m)| m.name == mi.name && m.kind == mi.kind && !m.is_abstract)
                });
                let Some((_, m)) = found else {
                    continue;
                };
                let mutable = self.p.method_mutates(m.func.id);
                let (sig, names) = self.method_sig(m, mutable)?;
                lines.push(format!("    {sig};"));
                sigs.push((sig, names));
            }
            out.push_str(&format!(
                "\n/// What `T extends {c}` needs of `T`.\ntrait {trait_name} {{\n{}\n}}\n",
                lines.join("\n")
            ));
            for n in impls {
                let nname = pascal(&n);
                let params = self
                    .p
                    .struct_info(&n)
                    .map(|s| s.type_params.clone())
                    .unwrap_or_default();
                let (header, args) = if params.is_empty() {
                    (String::new(), String::new())
                } else {
                    let list = params.join(", ");
                    (format!("<{list}>"), format!("<{list}>"))
                };
                let mut body = Vec::new();
                for (fname, t, setter) in &getters {
                    body.push(format!(
                        "    fn {fname}(&self) -> &{t} {{\n        &self.{fname}\n    }}"
                    ));
                    if *setter {
                        body.push(format!(
                            "    fn {fname}_mut(&mut self) -> &mut {t} {{\n        &mut self.{fname}\n    }}"
                        ));
                    }
                }
                for (sig, names) in &sigs {
                    let method = sig
                        .trim_start_matches("fn ")
                        .split('(')
                        .next()
                        .unwrap_or_default();
                    let call_args = std::iter::once("self".to_string())
                        .chain(names.iter().cloned())
                        .collect::<Vec<_>>()
                        .join(", ");
                    body.push(format!(
                        "    {sig} {{\n        {nname}::{method}({call_args})\n    }}"
                    ));
                }
                out.push_str(&format!(
                    "\nimpl{header} {trait_name} for {nname}{args} {{\n{}\n}}\n",
                    body.join("\n\n")
                ));
            }
        }
        Ok(out)
    }

    fn main_item(&mut self) -> GResult<()> {
        let info = self.p.funcs[&self.p.main_id].clone();
        self.blank();
        self.push_scope();
        self.fns.push(FnGen {
            id: self.p.main_id,
            returns_result: info.throws,
            ret_ty: Ty::Void,
            yield_ty: None,
            targets: Vec::new(),
            try_ctx: Vec::new(),
            in_ctor: false,
            this_name: "self",
            type_params: Vec::new(),
            bounds: Default::default(),
            class: None,
            labels: 0,
        });
        let stmts: Vec<&'a Stmt> = self
            .m
            .body
            .iter()
            .filter(|s| {
                !matches!(
                    s.kind,
                    StmtKind::Func(_)
                        | StmtKind::Class(_)
                        | StmtKind::Interface(_)
                        | StmtKind::TypeAlias(_)
                        | StmtKind::Enum(_)
                        | StmtKind::Empty
                        | StmtKind::Import(_)
                        | StmtKind::ExportNames(_)
                        | StmtKind::ExportFrom { .. }
                )
            })
            .collect();
        let body = self.capture(|g| {
            g.indent += 1;
            for s in &stmts {
                g.stmt(s)?;
            }
            if info.throws && (info.is_async || !g.p.uses_timers) {
                g.line("Ok(())");
            }
            g.indent -= 1;
            Ok(())
        });
        self.fns.pop();
        self.pop_scope();
        let body = body?;
        let ret = if info.throws {
            " -> Result<(), String>"
        } else {
            ""
        };
        let timers = if self.p.uses_timers {
            self.helper(Helper::Timers);
            true
        } else {
            false
        };
        if info.is_async {
            let h = self.helper(Helper::BlockOn);
            self.line(&format!("fn main(){ret} {{"));
            self.indent += 1;
            if timers {
                self.line(&format!("let result = {h}(async {{"));
                self.out.push_str(&indent_text(&body, 1));
                self.line("});");
                self.line("js_run_timers();");
                self.line("result");
            } else {
                self.line(&format!("{h}(async {{"));
                self.out.push_str(&indent_text(&body, 1));
                self.line("})");
            }
            self.indent -= 1;
            self.line("}");
        } else {
            self.line(&format!("fn main(){ret} {{"));
            self.out.push_str(&body);
            if timers {
                self.indent += 1;
                self.line("js_run_timers();");
                if info.throws {
                    self.line("Ok(())");
                }
                self.indent -= 1;
            }
            self.line("}");
        }
        Ok(())
    }
}

fn format_num(n: f64) -> String {
    if n.fract() == 0.0 {
        format!("{}", n as i64)
    } else {
        format!("{n}")
    }
}

fn uses_this(e: &Expr) -> bool {
    let mut found = false;
    visit_expr(e, &mut |x| {
        if matches!(x.kind, ExprKind::This) {
            found = true;
        }
    });
    found
}

/// Visits every sub-expression.
pub(super) fn visit_expr<'e>(e: &'e Expr, f: &mut dyn FnMut(&'e Expr)) {
    f(e);
    match &e.kind {
        ExprKind::Template { exprs, .. } | ExprKind::Seq(exprs) => {
            exprs.iter().for_each(|x| visit_expr(x, f))
        }
        ExprKind::Array(elems) => {
            for el in elems {
                if let ArrayElem::Expr(x) | ArrayElem::Spread(x) = el {
                    visit_expr(x, f);
                }
            }
        }
        ExprKind::Object(props) => {
            for p in props {
                if let PropValue::Expr(x) | PropValue::Spread(x) = &p.value {
                    visit_expr(x, f);
                }
            }
        }
        ExprKind::Unary { arg, .. } | ExprKind::Update { arg, .. } => visit_expr(arg, f),
        ExprKind::Binary { left, right, .. } | ExprKind::Logical { left, right, .. } => {
            visit_expr(left, f);
            visit_expr(right, f);
        }
        ExprKind::Assign { target, value, .. } => {
            if let AssignTarget::Expr(t) = target {
                visit_expr(t, f);
            }
            visit_expr(value, f);
        }
        ExprKind::Cond { test, cons, alt } => {
            visit_expr(test, f);
            visit_expr(cons, f);
            visit_expr(alt, f);
        }
        ExprKind::Call { callee, args, .. } | ExprKind::New { callee, args, .. } => {
            visit_expr(callee, f);
            args.iter().for_each(|a| visit_expr(&a.expr, f));
        }
        ExprKind::Member { obj, .. } => visit_expr(obj, f),
        ExprKind::Index { obj, index, .. } => {
            visit_expr(obj, f);
            visit_expr(index, f);
        }
        ExprKind::As(x, _)
        | ExprKind::NonNull(x)
        | ExprKind::TypeOf(x)
        | ExprKind::Void(x)
        | ExprKind::Delete(x)
        | ExprKind::Await(x) => visit_expr(x, f),
        ExprKind::Arrow(func) | ExprKind::Func(func) => {
            if let FnBody::Expr(x) = &func.body {
                visit_expr(x, f);
            }
        }
        _ => {}
    }
}

/// The expression with the given id inside a class (static field initializers).
fn find_expr(class: &Class, id: NodeId) -> Option<&Expr> {
    for m in &class.members {
        if let ClassMember::Field(f) = m
            && let Some(init) = &f.init
            && init.id == id
        {
            return Some(init);
        }
    }
    None
}

fn indent_text(text: &str, levels: usize) -> String {
    let pad = "    ".repeat(levels);
    text.lines()
        .map(|l| {
            if l.is_empty() {
                String::new()
            } else {
                format!("{pad}{l}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
        + "\n"
}

#[allow(dead_code)]
fn unused(_: Role) {}

/// A method of a `dyn` trait, as declared and as implemented.
struct TraitSig {
    name: String,
    self_param: &'static str,
    /// Name, Rust type, how it is passed, and its type.
    params: Vec<(String, String, Mode, Ty)>,
    ret: String,
}

impl TraitSig {
    /// `fn name(&self, x: T) -> R`, with `mut` before the parameters marked.
    fn text(&self, muts: &[bool]) -> String {
        let mut all = vec![self.self_param.to_string()];
        for (i, (name, t, _, _)) in self.params.iter().enumerate() {
            let m = if muts.get(i).copied().unwrap_or(false) {
                "mut "
            } else {
                ""
            };
            all.push(format!("{m}{name}: {t}"));
        }
        format!("fn {}({}){}", self.name, all.join(", "), self.ret)
    }
}
